function y = addParameterGroup(path, names, dataType, y, gotoTags)
if nargin < 5
    gotoTags = containers.Map('KeyType', 'char', 'ValueType', 'char');
end
for index = 1:numel(names)
    name = names{index};
    options = {'Value', name, 'SampleTime', '0.001', ...
        'Position', [35 y 165 y + 20]};
    if ~isempty(dataType)
        options = [options, {'OutDataTypeStr', dataType}]; %#ok<AGROW>
    end
    add_block('simulink/Sources/Constant', [path '/Cmd ' name], options{:});
    if isKey(gotoTags, name)
        add_block('simulink/Signal Routing/Goto', [path '/Goto ' name], ...
            'GotoTag', gotoTags(name), 'TagVisibility', 'global', ...
            'Position', [200 y 260 y + 20]);
        add_line(path, ['Cmd ' name '/1'], ['Goto ' name '/1']);
    else
        add_block('simulink/Sinks/Terminator', [path '/Term ' name], ...
            'Position', [200 y 220 y + 20]);
        add_line(path, ['Cmd ' name '/1'], ['Term ' name '/1']);
    end
    y = y + 26;
end
end

