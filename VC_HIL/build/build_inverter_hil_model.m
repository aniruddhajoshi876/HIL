function script = rxRetentionScript()
%RXRETENTIONSCRIPT Drain the channel-2 (VC bus) CAN Read FIFO and retain
%frames at this block's own rate (the CAN Read block's ts, 1 ms -- see
%ADDHARDWAREBOUNDARY). The VC transmits four control frames every 5 ms; a
%single FIFO pop every 5 ms fell behind the burst, so the receive FIFO
%backed up and the retained command was stale at best and, once the FIFO
%backed up, simply frozen -- frames genuinely sent were never read. Draining
%at 1 ms stays ahead of it. The CarMaker pedal demand (0x500) is retained
%separately by CARMAKERPEDALRETENTIONSCRIPT off its own channel-1 read.
%EPHORUS STATUS CYCLE (STATUSCYCLESCRIPT) keeps the state machine, plant,
%and CAN-write chain at the original 5 ms rate.
script = sprintf([ ...
    'function [rxObservationOut, rawControlDiag] = ephorusRxRetentionStep( ...\n' ...
    '    rxDataPresent, rxId, rxExtended, rxRemote, rxLength, rxData, ...\n' ...
    '    dropControlMask)\n' ...
    '%%#codegen\n' ...
    '%%EPHORUSRXRETENTIONSTEP Drain one CAN Read FIFO pop per call and\n' ...
    '%%retain it, at this block''s own 1 ms rate. See BUILD_INVERTER_HIL_\n' ...
    '%%MODEL''s RXRETENTIONSCRIPT for why: the VC''s four control frames\n' ...
    '%%every 5 ms outran a single 5 ms FIFO pop.\n' ...
    '%%\n' ...
    '%%A frame is ALWAYS passed, with DROP set when nothing was received.\n' ...
    '%%RECEIVECONTROLFRAME rejects a dropped frame without touching the\n' ...
    '%%bank, so the array stays fixed-size for code generation instead of\n' ...
    '%%growing and shrinking. Nothing is fabricated: no data present means\n' ...
    '%%no command retained.\n' ...
    '%%\n' ...
    '%%BANK/STATUSBANK/TICKMS are persistent so retention survives across\n' ...
    '%%calls, exactly as the single combined block this was split out of\n' ...
    '%%used to carry it.\n' ...
    'persistent bank statusBank tickMs\n' ...
    'if isempty(bank)\n' ...
    '    bank = initialDecoderBank();\n' ...
    '    statusBank = initialStatusBank();\n' ...
    '    tickMs = uint32(0);\n' ...
    'end\n' ...
    '%%(:)'' normalises the bus Data element to a 1x8 row regardless of the\n' ...
    '%%orientation Simulink propagates, matching the proven pattern in the\n' ...
    '%%IO614 CAN visibility test decoder.\n' ...
    'payload = uint8(rxData(:))'';\n' ...
    'frame = struct( ...\n' ...
    '    ''id'', uint32(rxId), ...\n' ...
    '    ''dlc'', uint8(rxLength), ...\n' ...
    '    ''payload'', payload, ...\n' ...
    '    ''isExtended'', logical(rxExtended), ...\n' ...
    '    ''isRemote'', logical(rxRemote), ...\n' ...
    '    ''drop'', ~logical(rxDataPresent));\n' ...
    '%%TEMPORARY DIAGNOSTIC (2026-08-19): see INITIALDECODERBANK for why\n' ...
    '%%these counts are monotonic and bank-wide rather than one more\n' ...
    '%%polled-and-overwritten field. Counted from the RAW, pre-mask frame\n' ...
    '%%so the drop-mask tunable cannot hide a genuine wire mismatch from\n' ...
    '%%view. Remove this block once the control channels'' permanent\n' ...
    '%%rejection is root-caused.\n' ...
    'if ~frame.drop\n' ...
    '    diagProtocol = protocol();\n' ...
    '    if any(diagProtocol.controlIds == frame.id)\n' ...
    '        bank.rawControlMatchCount = bank.rawControlMatchCount + uint32(1);\n' ...
    '        bank.rawControlLastId = frame.id;\n' ...
    '        bank.rawControlLastDlc = frame.dlc;\n' ...
    '        bank.rawControlLastExtended = uint8(frame.isExtended);\n' ...
    '        bank.rawControlLastRemote = uint8(frame.isRemote);\n' ...
    '    end\n' ...
    'end\n' ...
    'statusBank = receiveStatusFrame(statusBank, frame, tickMs);\n' ...
    '%%The CAN control-frame drop mask (Fix 4) is applied to a COPY of the\n' ...
    '%%received frame used only for retention -- STATUSBANK above already\n' ...
    '%%saw the unmodified FRAME, so this mask cannot affect the received-\n' ...
    '%%status-frame path, only whether a control frame is retained into the\n' ...
    '%%decoder bank.\n' ...
    '[controlFrame, maskDropped] = applyControlDropMask(frame, uint8(dropControlMask));\n' ...
    '%%TEMPORARY DIAGNOSTIC (2026-08-19): isolates the drop-mask tunable as\n' ...
    '%%a cause independent of everything downstream of it.\n' ...
    'if maskDropped\n' ...
    '    bank.maskForcedDropCount = bank.maskForcedDropCount + uint32(1);\n' ...
    'end\n' ...
    'bank = receiveControlFrame(bank, controlFrame, tickMs);\n' ...
    '%%RXOBSERVATION is taken BEFORE the tick advances, so the ages it\n' ...
    '%%reports are measured against the same tick the frame above was\n' ...
    '%%retained at. Advancing first would make a frame received this step\n' ...
    '%%appear one period old.\n' ...
    'controlRows = rxObservation(bank, tickMs);\n' ...
    'statusRows = statusObservation(statusBank, tickMs);\n' ...
    'rxObservationOut = zeros(13, 14);\n' ...
    'rxObservationOut(1:4, :) = controlRows;\n' ...
    'rxObservationOut(5:13, 1:11) = statusRows;\n' ...
    '%%TEMPORARY DIAGNOSTIC (2026-08-19): see INITIALDECODERBANK/\n' ...
    '%%RAWCONTROLDIAGNOSTICS. Remove once root-caused.\n' ...
    'rawControlDiag = rawControlDiagnostics(bank);\n' ...
    '%%TICKMS is REAL MILLISECONDS, advanced by 1 per call at this block''s\n' ...
    '%%own 1 ms period. The MOD wrap matches DECODERSNAPSHOT''s rollover-\n' ...
    '%%safe modulo arithmetic; MATLAB uint32 addition otherwise SATURATES\n' ...
    '%%(the generated C++ made that explicit: if (t + 1U < t) { t =\n' ...
    '%%MAX_uint32_T; }) and would freeze the counter at intmax rather than\n' ...
    '%%roll over, which would freeze every retained frame at age 0 forever\n' ...
    '%%and stop command timeouts from firing entirely.\n' ...
    'tickMs = uint32(mod(double(tickMs) + 1, 4294967296));\n' ...
    'end\n']);
end

function script = carMakerPedalRetentionScript()
%CARMAKERPEDALRETENTIONSCRIPT Drain the channel-1 (CarMaker bus) CAN Read
%FIFO and retain the freshness-checked 0x500 CarMakerPedalDemand at this
%block's own 1 ms rate. Split out of RXRETENTIONSCRIPT when the single
%bridged bus was divided into a CarMaker bus (channel 1) and a VC bus
%(channel 2): 0x500 only exists on channel 1, and EPHORUS RX RETENTION now
%only sees VC control frames on channel 2. The frame struct and (:)'' payload
%normalisation match RXRETENTIONSCRIPT exactly; the retain/freshness logic
%is the existing RECEIVEPEDALDEMANDFRAME / PEDALDEMANDSNAPSHOT pair,
%unchanged. Output is the same 3-element vector the hardware-boundary pedal
%selector consumes through the CarMakerPedalDemand global Goto.
script = sprintf([ ...
    'function pedalDemand = carMakerPedalRetentionStep( ...\n' ...
    '    rxDataPresent, rxId, rxExtended, rxRemote, rxLength, rxData)\n' ...
    '%%#codegen\n' ...
    '%%CARMAKERPEDALRETENTIONSTEP One channel-1 FIFO pop per 1 ms call,\n' ...
    '%%retained and freshness-checked. See BUILD_INVERTER_HIL_MODEL''s\n' ...
    '%%CARMAKERPEDALRETENTIONSCRIPT.\n' ...
    'persistent pedalBank tickMs\n' ...
    'if isempty(pedalBank)\n' ...
    '    pedalBank = initialPedalDemandBank();\n' ...
    '    tickMs = uint32(0);\n' ...
    'end\n' ...
    'payload = uint8(rxData(:))'';\n' ...
    'frame = struct( ...\n' ...
    '    ''id'', uint32(rxId), ...\n' ...
    '    ''dlc'', uint8(rxLength), ...\n' ...
    '    ''payload'', payload, ...\n' ...
    '    ''isExtended'', logical(rxExtended), ...\n' ...
    '    ''isRemote'', logical(rxRemote), ...\n' ...
    '    ''drop'', ~logical(rxDataPresent));\n' ...
    'pedalBank = receivePedalDemandFrame(pedalBank, frame, tickMs);\n' ...
    'pedalSnapshot = pedalDemandSnapshot(pedalBank, tickMs);\n' ...
    '%% [percent throttle, percent brake, atomic CAN ownership].\n' ...
    '%% On loss the selector returns to GUI; the GUI immediately writes zero\n' ...
    '%% on its observed handover, preventing stale slider pickup.\n' ...
    'pedalDemand = [pedalSnapshot.throttlePercent pedalSnapshot.brakePercent double(pedalSnapshot.ownsPedals)];\n' ...
