function script = pedalFallbackZeroHoldScript()
script = sprintf([ ...
    'function [throttleOut,brakeOut] = pedalFallbackZeroHold( ...\n' ...
    '    throttleIn, brakeIn, canOwnsPedals)\n' ...
    '%%PEDALFALLBACKZEROHOLD Hold the non-CAN pedal fallback at zero after\n' ...
    '%%CAN pedal authority is lost, until both GUI values return to zero.\n' ...
    '%%\n' ...
    '%%   Without this latch the source switches fall back to whatever the\n' ...
    '%%   GUI dictionary entries hold, so a slider left mid-travel would\n' ...
    '%%   step AO01-AO04 into the real VC the moment the CAN link dropped.\n' ...
    '%%   Zeroing in the GUI instead leaves a window one poll wide; this is\n' ...
    '%%   the model-side guarantee that closes it. Re-arming on the sliders\n' ...
    '%%   returning to zero keeps recovery automatic - no operator re-arm -\n' ...
    '%%   while making it impossible to resume at a stale non-zero demand.\n' ...
    '%%#codegen\n' ...
    'persistent armed\n' ...
    'if isempty(armed)\n' ...
    '    armed = false;\n' ...
    'end\n' ...
    'zeroTolerance = 0.001;\n' ...
    'if canOwnsPedals ~= 0\n' ...
    '    %% CAN is driving; the switches ignore these outputs. Arm so that the\n' ...
    '    %% next loss of authority is caught even if it happens next step.\n' ...
    '    armed = true;\n' ...
    '    throttleOut = throttleIn;\n' ...
    '    brakeOut = brakeIn;\n' ...
    'elseif armed\n' ...
    '    if throttleIn <= zeroTolerance && brakeIn <= zeroTolerance\n' ...
    '        armed = false;\n' ...
    '        throttleOut = throttleIn;\n' ...
    '        brakeOut = brakeIn;\n' ...
    '    else\n' ...
    '        throttleOut = 0;\n' ...
    '        brakeOut = 0;\n' ...
    '    end\n' ...
    'else\n' ...
    '    throttleOut = throttleIn;\n' ...
    '    brakeOut = brakeIn;\n' ...
    'end\n']);
end
function script = pedalCalibrationScript()
script = sprintf([ ...
    'function [ao1,ao2,ao3,ao4] = pedalVoltageCalibration( ...\n' ...
    '    throttle, brake, released1, pressed1, released2, pressed2, ...\n' ...
    '    released3, pressed3, released4, pressed4)\n' ...
    '%%PEDALVOLTAGECALIBRATION Map GUI throttle/brake fractions (0-1) to\n' ...
    '%%the four redundant IO183 analog-output voltages using the\n' ...
    '%%calibrated released/pressed endpoints.\n' ...
    '%%\n' ...
    '%%   HIL_CAL_PEDALS_RELEASED_V*/PRESSED_V* ship as NaN precisely so an\n' ...
    '%%   uncalibrated channel is detectable rather than silently plausible\n' ...
    '%%   (INVERTER_HIL_PLAN.MD S3.1 requires each endpoint be measured at\n' ...
    '%%   the connected VCU pin under load). An uncalibrated or out-of-range\n' ...
    '%%   channel therefore drives 0 V -- the same level the IO183 initial\n' ...
    '%%   and reset values use -- instead of propagating NaN into a DAC.\n' ...
    'ao1 = calibratedVolts(released1, pressed1, throttle);\n' ...
    'ao2 = calibratedVolts(released2, pressed2, throttle);\n' ...
    'ao3 = calibratedVolts(released3, pressed3, brake);\n' ...
    'ao4 = calibratedVolts(released4, pressed4, brake);\n' ...
    'end\n' ...
    '\n' ...
    'function volts = calibratedVolts(releasedV, pressedV, fraction)\n' ...
    'if ~isfinite(releasedV) || ~isfinite(pressedV) || ~isfinite(fraction)\n' ...
    '    volts = 0;\n' ...
    '    return\n' ...
    'end\n' ...
    'bounded = min(max(fraction, 0), 1);\n' ...
    'volts = releasedV + (pressedV - releasedV) * bounded;\n' ...
    '%%The IO183 analog outputs are configured for the 0..5 V range.\n' ...
    'volts = min(max(volts, 0), 5);\n' ...
    'end\n']);
end

