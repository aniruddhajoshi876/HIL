function build_inverter_hil_model(force)
%BUILD_INVERTER_HIL_MODEL Generate the R2024b model and data dictionary.

if nargin < 1
    force = false;
end
if ~(islogical(force) && isscalar(force))
    error('inverterhil:InvalidBuildOption', 'force must be a logical scalar.');
end

root = inverter_hil_setup();
model = 'inverter_hil';
modelPath = fullfile(root, [model '.slx']);
dictionaryPath = fullfile(root, [model '.sldd']);

if bdIsLoaded(model)
    close_system(model, 0);
end
prepareOutput(modelPath, force);
prepareOutput(dictionaryPath, force);

createDictionary(dictionaryPath);
new_system(model);
cleanupModel = onCleanup(@() closeIfLoaded(model));
set_param(model, ...
    'DataDictionary', [model '.sldd'], ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.001', ...
    'StartTime', '0.0', ...
    'StopTime', 'inf', ...
    'SystemTargetFile', 'speedgoat.tlc', ...
    'DefaultParameterBehavior', 'Tunable', ...
    'SignalLogging', 'on', ...
    'InitFcn', 'enforceHardwarePreflight(bdroot);');

addArchitecture(model);
addHardwareBoundary(model);
addGuiCommandParameters(model);
addAnnotation(model, ...
    ['INVERTER HIL - R2024b\n' ...
     'CAN status packing and IO183 pedal/digital hardware I/O are real, ' ...
     'not placeholders; gated by Commented + hil_hardware_preflight_complete\n' ...
     'Torque scale RESOLVED 2026-08-02: 1/256 Nm/count (vcu256, verified), ' ...
     'per MFE26-VC firmware ephorus_driver.hpp:55; 1/512 retained only as a ' ...
     'known-wrong profile'], ...
    [40 20 900 96], 'yellow');

save_system(model, modelPath, 'SaveModelWorkspace', false);
set_param(model, 'SimulationCommand', 'update');
save_system(model, modelPath);

% CREATEDICTIONARY seeds every pedal endpoint at NaN so an uncalibrated
% channel is detectable. That is right for a fresh dictionary and wrong for a
% rebuild: it silently discarded the applied calibration once, and a
% discarded endpoint fails quietly (PEDALVOLTAGECALIBRATION drives 0 V, so
% the GUI sliders still move while the VCU pin does not). Re-applying from
% version-controlled constants here makes a rebuild non-destructive.
apply_pedal_calibration(dictionaryPath);

% NOTE: on this branch the VCU in the loop is the real MFE26-VC, so the
% virtual VCU is deliberately NOT built into the application. The
% add_virtual_vcu_to_model / patch_virtual_vcu_* integration hooks live on
% branch `virtual-vcu` and must not be reintroduced here -- IO614 Port A
% stays free for the real VCU's traffic rather than a Speedgoat-side
% stand-in.

fprintf('Created %s and %s with MATLAB %s.\n', ...
    modelPath, dictionaryPath, version('-release'));
end

function prepareOutput(path, force)
if isfile(path)
    if ~force
        error('inverterhil:ArtifactExists', ...
            'Artifact exists; call build_inverter_hil_model(true): %s', path);
    end
    delete(path);
end
end

function createDictionary(path)
dictionary = Simulink.data.dictionary.create(path);
cleanup = onCleanup(@() close(dictionary));
section = getSection(dictionary, 'Design Data');

addEntry(section, 'hil_model_release', 'R2024b');
addEntry(section, 'hil_base_sample_s', parameter(1e-3, 1e-3, 1e-3));
addEntry(section, 'hil_status_sample_s', parameter(statusPeriodS(), ...
    statusPeriodS(), statusPeriodS()));
% Each GUI-owned tunable below is a scalar dictionary entry with the exact
% flatPath name +INVERTERHILGUI/PARAMETERCONTRACT.M declares, so
% DISCOVERCONTRACT resolves every required logical name once the block
% referencing it (see ADDGUICOMMANDPARAMETERS) survives code generation.
addEntry(section, 'hil_cmd_pedals_throttle', parameter(0, 0, 1));
addEntry(section, 'hil_cmd_pedals_brake', parameter(0, 0, 1));
% Synchronized MTi-680G/Bosch LWS sensor stimulus. The steering bound is the
% Bosch LWS measuring range (+/-780 deg, see REFERENCES/SENSORS and
% INVERTER_HIL/STEERING-SENSOR/PROTOCOL.MD), not an arbitrary GUI limit, so
% the dictionary clamp and the encoder's range check agree.
addEntry(section, 'hil_cmd_steering_angle_deg', parameter(0, -780, 780));
addEntry(section, 'hil_cmd_steering_dropout', parameter(false, false, true));
addEntry(section, 'hil_cmd_steering_stale', parameter(false, false, true));
addEntry(section, 'hil_cmd_steering_malformed', parameter(false, false, true));
addEntry(section, 'hil_cmd_steering_invalid_status', ...
    parameter(false, false, true));
addEntry(section, 'hil_cmd_steering_angle_sentinel', ...
    parameter(false, false, true));
addEntry(section, 'hil_cmd_steering_speed_sentinel', ...
    parameter(false, false, true));
% Monotonic request token. A changed value starts the target-side ordered
% reset (0x05) -> checked wait -> zero (0x03) sequence; the GUI never writes
% command bytes directly and therefore cannot reproduce the firmware's
% queue-two/transmit-once bug.
addEntry(section, 'hil_cmd_steering_calibration_sequence', ...
    parameter(uint32(0), uint32(0), intmax('uint32')));
addEntry(section, 'hil_cmd_imu_dropout', parameter(false, false, true));
addEntry(section, 'hil_cmd_imu_stale', parameter(false, false, true));
addEntry(section, 'hil_cmd_imu_malformed', parameter(false, false, true));
addEntry(section, 'hil_cmd_pedals_plausibility_override', ...
    parameter(false, false, true));
addEntry(section, 'hil_cmd_digital_main_button', parameter(false, false, true));
addEntry(section, 'hil_cmd_digital_cooling_switch', ...
    parameter(false, false, true));
addEntry(section, 'hil_cmd_digital_shutdown_feedback', ...
    parameter(false, false, true));
addEntry(section, 'hil_cmd_digital_precharge_sequence', ...
    parameter(uint32(0), uint32(0), intmax('uint32')));
addEntry(section, 'hil_cmd_digital_main_button_sequence', ...
    parameter(uint32(0), uint32(0), intmax('uint32')));
addEntry(section, 'hil_cmd_dc_link12_v', ...
    parameter(0, 0, 1023.984375));
addEntry(section, 'hil_cmd_dc_link34_v', ...
    parameter(0, 0, 1023.984375));
for channel = 1:4
    addEntry(section, sprintf('hil_cmd_inverter%d_load_nm', channel), ...
        parameter(0, -200, 200));
    addEntry(section, sprintf('hil_cmd_inverter%d_connected', channel), ...
        parameter(true, false, true));
    addEntry(section, sprintf('hil_cmd_inverter%d_fault_mask', channel), ...
        parameter(uint32(0), uint32(0), intmax('uint32')));
end
addEntry(section, 'hil_cmd_can_drop_control_mask', ...
    parameter(uint8(0), uint8(0), uint8(255)));
addEntry(section, 'hil_cmd_can_drop_status_mask', ...
    parameter(uint16(0), uint16(0), uint16(65535)));
addEntry(section, 'hil_cmd_gui_heartbeat', parameter(uint32(0), ...
    uint32(0), intmax('uint32')));
for channel = 1:4
    addEntry(section, sprintf('hil_cal_pedals_released_v%d', channel), ...
        parameter(NaN, 0, 5));
    addEntry(section, sprintf('hil_cal_pedals_pressed_v%d', channel), ...
        parameter(NaN, 0, 5));
end

addEntry(section, 'hil_safe_analog_reset_v', parameter(zeros(1, 4), ...
    zeros(1, 4), zeros(1, 4)));
addEntry(section, 'hil_safe_digital_reset', parameter(false(1, 8), false, false));

addEntry(section, 'hil_control_can_ids', uint32(hex2dec( ...
    {'186', '196', '1A6', '1B6'})));
addEntry(section, 'hil_status_can_ids', uint32(hex2dec( ...
    {'383', '385', '393', '395', '3A3', '3A5', '3B3', '3B5', '400'})));
% Torque scale RESOLVED 2026-08-02 by firmware evidence (see
% INVERTERHIL.PROTOCOL's torqueProfiles.vcu256 comment): 1/256 Nm/count,
% profile 'ephorus3-v1.03-candidate-1over256', matching
% +INVERTERHIL/DEFAULTCALIBRATION.M's default.
addEntry(section, 'hil_torque_profile_id', ...
    'ephorus3-v1.03-candidate-1over256');
addEntry(section, 'hil_torque_scale_nm_per_count', 1 / 256);
addEntry(section, 'hil_torque_scale_verified', true);
% Operator-attested preflight: electrical levels, grounds, J3 isolation,
% polarity, and CAN termination on this IO183/IO614 bench have been
% verified hands-on (not by an automated check). See
% INVERTERHIL.ENFORCEHARDWAREPREFLIGHT and the Hardware I/O subsystem's
% Commented flag below, which this value gates.
addEntry(section, 'hil_hardware_preflight_complete', true);
addEntry(section, 'hil_torque_results_provisional', true);

saveChanges(dictionary);
end

function value = parameter(initialValue, minimum, maximum)
value = Simulink.Parameter(initialValue);
value.Min = double(min(minimum(:)));
value.Max = double(max(maximum(:)));
value.CoderInfo.StorageClass = 'SimulinkGlobal';
end

function addArchitecture(model)
% Only "Ephorus System Status" is built here. This file previously also
% built a "Test Inputs" / "Fault Injection" / "Pedal Sensor Emulation" /
% "VCU Digital Interface" / "IO614 CAN Interface" / "Ephorus Channel 1-4" /
% "Measurements and Logging" tree that existed purely to draw an MIL-style
% architecture diagram: every one of those subsystems terminated its inputs
% immediately and emitted only constant zeros, with no path into the real
% CAN/state-machine/plant logic below. Removed rather than left as dead
% code -- the real hardware I/O lives in ADDHARDWAREBOUNDARY, the
% real GUI-commanded values in ADDGUICOMMANDPARAMETERS, and the real
% decode/state-machine/plant/pack logic inside "Ephorus System Status"
% itself (EPHORUS RX RETENTION and the EPHORUS STATUS CYCLE MATLAB Function
% block, both built by BUILDSYSTEMSTATUS below).
add_block('simulink/Ports & Subsystems/Subsystem', ...
    [model '/Ephorus System Status'], 'Position', [960 210 1180 430]);
buildSystemStatus([model '/Ephorus System Status']);

% The hardware boundary transmits these exact payloads over CAN. It reads
% them through this global Goto rather than an Inport so the boundary stays
% port-free and can be commented out (its safety gate) without disturbing
% the rest of the diagram -- and rather than recomputing the model step,
% which would create a second, independently-diverging state machine.
add_block('simulink/Signal Routing/Goto', [model '/Status Payloads Goto'], ...
    'GotoTag', 'EphorusStatusPayloads', 'TagVisibility', 'global', ...
    'Position', [1220 300 1300 320]);
add_line(model, 'Ephorus System Status/1', 'Status Payloads Goto/1', ...
    'autorouting', 'on');

% The received-frame observation has no consumer inside the model -- it
% exists purely so the GUI can READ it -- but a subsystem output port must
% still be connected or the diagram will not update. A Terminator is the
% established pattern this file already uses everywhere for exactly this
% (see ADDGUICOMMANDPARAMETERS's Constant->Terminator pairs): a real
% consumer that keeps a signal live through code generation without
% implying anything downstream depends on its value.
%
% DATALOGGING is deliberately NOT set here, though an earlier version of
% this file did set it (alongside TESTPOINT) believing the Terminator alone
% might not survive optimization. That combination reliably crashed the
% HOST MATLAB process -- not the target -- with an access violation inside
% LIBMWSLRESTIME_XCP.DLL's AsyncQueue::write/StreamingList teardown, every
% time STOP(TARGET) ran while this port's logged stream was active
% (confirmed against four separate matlab_crash_dump.* traces, same top two
% frames each time; GETCRASHSTACK on the target found no corresponding
% target-side fault, so the deployed application itself was never at fault).
% DataLogging opens a persistent host-side signal-streaming subscription
% distinct from GETSIGNAL's own one-shot reads, and it is that subscription
% whose teardown was crashing. The Terminator was always sufficient by
% itself -- this file's own established pattern proves it -- so there was
% nothing to gain from DataLogging and a live MATLAB session to lose.
add_block('simulink/Sinks/Terminator', ...
    [model '/Received Control Observation Terminator'], ...
    'Position', [1220 350 1240 370]);
add_line(model, 'Ephorus System Status/2', ...
    'Received Control Observation Terminator/1', 'autorouting', 'on');

% Port 3 (the four measured Rail Monitor AI channels, Fix 1) has no
% consumer inside the model either -- it exists purely so the GUI can READ
% it -- so it gets the same Terminator treatment as port 2 above, for the
% same reason: a subsystem output port must be connected for the diagram to
% update, and a Terminator is a real, permanent consumer that implies
% nothing about downstream use.
add_block('simulink/Sinks/Terminator', ...
    [model '/Analog Input Telemetry Terminator'], ...
    'Position', [1220 390 1240 410]);
add_line(model, 'Ephorus System Status/3', ...
    'Analog Input Telemetry Terminator/1', 'autorouting', 'on');
% Port 5 is the shared vehicle state (see BUILDSTATUSCYCLE's Port 5 note).
% Published as a global Goto so the synchronized MTi/LWS encoders inside
% the hardware boundary's CAN interface (ADDHARDWAREBOUNDARY) observe the
% same tick the inverter plant produced. A Goto is a real consumer, so
% unlike ports 2 and 3 above this needs no Terminator. Port 4
% (TRANSMITCOUNT) is read by the GUI straight off the subsystem port and
% has no model-level consumer either.
add_block('simulink/Signal Routing/Goto', [model '/Vehicle State Goto'], ...
    'GotoTag', 'HILSharedVehicleState', 'TagVisibility', 'global', ...
    'Position', [1220 430 1300 450]);
add_line(model, 'Ephorus System Status/5', 'Vehicle State Goto/1', ...
    'autorouting', 'on');
add_block('simulink/Sinks/Terminator', ...
    [model '/CarMaker Pedal Demand Terminator'], ...
    'Position', [1220 470 1240 490]);
add_line(model, 'Ephorus System Status/6', ...
    'CarMaker Pedal Demand Terminator/1', 'autorouting', 'on');
end

function buildSystemStatus(path)
clearSubsystem(path);
% This cycle is computed by INVERTERHIL.STEPMODEL using its own persistent
% state, driven by the received CAN frames retained below -- not by
% combining any per-channel Simulink block outputs.

% Received VC control frames, published by the hardware boundary's channel-2
% (VC bus) read. Retained in EPHORUS RX RETENTION below at the CAN Read
% block's own rate (1 ms, ADDHARDWAREBOUNDARY): the VC transmits four
% control frames every 5 ms, and a single FIFO pop every 5 ms fell behind
% the burst -- the receive FIFO backed up, so the retained command was stale
% at best and, once the FIFO backed up, simply frozen: frames genuinely sent
% were never read. Draining at 1 ms stays ahead of it. The CarMaker pedal
% demand (0x500) arrives on its OWN channel-1 read and is retained by
% CARMAKER PEDAL RETENTION below, not here. EPHORUS STATUS CYCLE further
% below keeps the state machine, plant, and CAN-write chain at the ORIGINAL
% 5 ms status-cycle rate, unchanged -- see that block for why it is not also
% sped up.
rxTags = {'EphorusRxDataPresent', 'EphorusRxId', 'EphorusRxExtended', ...
    'EphorusRxRemote', 'EphorusRxLength', 'EphorusRxData'};
for index = 1:numel(rxTags)
    fromName = sprintf('%s From', rxTags{index});
    add_block('simulink/Signal Routing/From', [path '/' fromName], ...
        'GotoTag', rxTags{index}, ...
        'Position', [60, 30 + 30 * index, 220, 50 + 30 * index]);
end
% The CAN control-frame drop mask (Fix 4) moves here from EPHORUS STATUS
% CYCLE's external inputs below: masking now happens where retention
% happens. Its GUI Command Parameters source already runs at the model's
% 1 ms base rate, the same rate this block now runs at, so no Rate
% Transition is needed for it (contrast the externalTags loop below, which
% still crosses from 1 ms into the 5 ms status-cycle rate).
dropControlFromName = 'GuiCmdCanDropControlMask From';
add_block('simulink/Signal Routing/From', [path '/' dropControlFromName], ...
    'GotoTag', 'GuiCmdCanDropControlMask', ...
    'Position', [60, 30 + 30 * (numel(rxTags) + 1), 220, ...
    50 + 30 * (numel(rxTags) + 1)]);

retentionFcnPath = [path '/Ephorus RX Retention'];
add_block('simulink/User-Defined Functions/MATLAB Function', retentionFcnPath, ...
    'Position', [250 45 430 220]);
setMatlabFunctionScript(retentionFcnPath, rxRetentionScript());
for index = 1:numel(rxTags)
    add_line(path, sprintf('%s From/1', rxTags{index}), ...
        sprintf('Ephorus RX Retention/%d', index), 'autorouting', 'on');
end
add_line(path, [dropControlFromName '/1'], ...
    sprintf('Ephorus RX Retention/%d', numel(rxTags) + 1), 'autorouting', 'on');

% CARMAKER PEDAL RETENTION -- the sole CarMaker pedal source. Fed by the
% hardware boundary's channel-1 (CarMaker bus) read, it drains that FIFO and
% retains the freshness-checked 0x500 CarMakerPedalDemand at its own 1 ms
% rate (RECEIVEPEDALDEMANDFRAME / PEDALDEMANDSNAPSHOT). Split out of EPHORUS
% RX RETENTION when the bus was split in two: that block now only sees VC
% control frames on channel 2, and 0x500 only exists on channel 1. Output is
% the same 3-element [throttlePercent, brakePercent, ownsPedals] vector the
% hardware-boundary pedal selector already consumes through the
% CarMakerPedalDemand global Goto; it never enters the 5-ms plant/status
% path and cannot alter the Ephorus decoder semantics.
carMakerRetentionPath = [path '/CarMaker Pedal Retention'];
carMakerRxTags = {'CarMakerRxDataPresent', 'CarMakerRxId', ...
    'CarMakerRxExtended', 'CarMakerRxRemote', 'CarMakerRxLength', ...
    'CarMakerRxData'};
for index = 1:numel(carMakerRxTags)
    fromName = sprintf('%s From', carMakerRxTags{index});
    add_block('simulink/Signal Routing/From', [path '/' fromName], ...
        'GotoTag', carMakerRxTags{index}, ...
        'Position', [60, 320 + 30 * index, 220, 340 + 30 * index]);
end
add_block('simulink/User-Defined Functions/MATLAB Function', ...
    carMakerRetentionPath, 'Position', [250 330 430 470]);
setMatlabFunctionScript(carMakerRetentionPath, carMakerPedalRetentionScript());
for index = 1:numel(carMakerRxTags)
    add_line(path, sprintf('%s From/1', carMakerRxTags{index}), ...
        sprintf('CarMaker Pedal Retention/%d', index), 'autorouting', 'on');
end
add_block('simulink/Signal Routing/Goto', [path '/CarMaker Pedal Demand Goto'], ...
    'GotoTag', 'CarMakerPedalDemand', 'TagVisibility', 'global', ...
    'Position', [450 390 570 410]);
add_line(path, 'CarMaker Pedal Retention/1', 'CarMaker Pedal Demand Goto/1', ...
    'autorouting', 'on');

% One Rate Transition brings EPHORUS RX RETENTION's flattened 13x14
% observation matrix from its 1 ms rate down to EPHORUS STATUS CYCLE's
% 5 ms rate -- the same zero-order-hold pattern the externalTags loop below
% already uses for GUI commands crossing the same two rates.
obsRtPath = [path '/Ephorus RX Observation RT'];
add_block('simulink/Signal Attributes/Rate Transition', obsRtPath, ...
    'Position', [460 60 480 80]);
add_line(path, 'Ephorus RX Retention/1', 'Ephorus RX Observation RT/1', ...
    'autorouting', 'on');

fcnPath = [path '/Ephorus Status Cycle'];
add_block('simulink/User-Defined Functions/MATLAB Function', fcnPath, ...
    'Position', [520 45 700 220]);
setMatlabFunctionScript(fcnPath, statusCycleScript());
add_line(path, 'Ephorus RX Observation RT/1', 'Ephorus Status Cycle/1', ...
    'autorouting', 'on');

add_block('simulink/Sinks/Out1', [path '/OrderedStatusPayloads'], ...
    'Port', '1', 'Position', [745 60 775 80]);
add_line(path, 'Ephorus Status Cycle/1', 'OrderedStatusPayloads/1');

% Port 2 publishes what the target actually RECEIVED (rows 1:4 are control
% RX; rows 5:13 are inverter status RX), still at the 5 ms rate this port
% always ran at -- that cadence was never the bottleneck; CAN READ popping
% the FIFO fast enough was. GETSIGNAL can only read signals on wires, so
% without this port the GUI has no way to observe received traffic at all.
% Terminated rather than left unconnected because nothing in the model
% consumes it; the GUI reads the port directly.
add_block('simulink/Sinks/Out1', [path '/ReceivedControlObservation'], ...
    'Port', '2', 'Position', [745 120 775 140]);
add_line(path, 'Ephorus Status Cycle/2', 'ReceivedControlObservation/1');

% Also published as a global Goto so CARMAKER TELEMETRY PAYLOADS (inside
% ADDHARDWAREBOUNDARY) can read the VC's actual retained control-frame
% commands directly, rather than Speedgoat's own simulated 3X3 status echo
% that subsystem used to read. Same signal ReceivedControlObservation
% above exposes to the GUI; this is a second consumer, not a second
% computation.
add_block('simulink/Signal Routing/Goto', ...
    [path '/Ephorus Rx Observation Goto'], ...
    'GotoTag', 'EphorusRxObservation', 'TagVisibility', 'global', ...
    'Position', [790 120 900 140]);
add_line(path, 'Ephorus Status Cycle/2', 'Ephorus Rx Observation Goto/1', ...
    'autorouting', 'on');

% Port 6 exposes the retained percent pair and atomic CAN-ownership flag to
% the GUI. It is intentionally the 1-ms retainer output, not a parameter:
% the GUI observes the same freshness decision that drives the selector.
% Sourced from CARMAKER PEDAL RETENTION (channel-1 CarMaker bus) since the
% bus split moved the pedal demand off EPHORUS RX RETENTION's path.
add_block('simulink/Sinks/Out1', [path '/CarMakerPedalDemandLive'], ...
    'Port', '6', 'Position', [745 275 775 295]);
add_line(path, 'CarMaker Pedal Retention/1', 'CarMakerPedalDemandLive/1');

% Port 7: TEMPORARY DIAGNOSTIC (2026-08-19). RAWCONTROLDIAG straight off
% EPHORUS RX RETENTION's second output -- see RXRETENTIONSCRIPT and
% INITIALDECODERBANK. Wired directly rather than through EPHORUS STATUS
% CYCLE for the same reason port 6 is: it is the 1 ms retainer's own
% output, and routing it through the 5 ms status-cycle function would
% require widening that function's fixed interface for a signal meant to
% be removed once the control channels' permanent rejection is
% root-caused.
add_block('simulink/Sinks/Out1', [path '/ControlDropDiagnostics'], ...
    'Port', '7', 'Position', [745 310 775 330]);
add_line(path, 'Ephorus RX Retention/2', 'ControlDropDiagnostics/1');

% Port 3: the four IO183 Rail Monitor AI channels, read back into "measured
% pedal voltage" GUI telemetry (see PINOUTS.MD S4.2 and
% ADDHARDWAREBOUNDARY's Analog Inputs Goto). A straight passthrough with no
% logic of its own -- not part of either MATLAB Function block above -- so
% it is wired here as a separate From/Out1 pair rather than as another
% chart input, per Fix 1's explicit instruction not to feed this into
% INVERTERHIL.STEPMODEL/the plant.
add_block('simulink/Signal Routing/From', [path '/Analog Inputs From'], ...
    'GotoTag', 'AnalogInputsV', 'Position', [300 240 420 260]);
% AnalogInputsV is a bare passthrough with no other consumer in the model
% (same shape as the Virtual VCU state observers PATCH_VIRTUAL_VCU_STATE_
% OUTPUTS.M documents), so Simulink's block-IO optimization collapses its
% storage onto the upstream signal and GETSIGNAL on the Out1 below fails
% with "Add a SignalCopy block". Fix is the same one that script uses: a
% Signal Conversion block (ConversionOutput='Signal copy') with its output
% port TestPoint='on', which forces independent, non-optimizable storage.
copyBlock = add_block('simulink/Signal Attributes/Signal Conversion', ...
    [path '/Analog Inputs Signal Copy'], 'ConversionOutput', 'Signal copy', ...
    'Position', [445 240 475 260]);
copyPorts = get_param(copyBlock, 'PortHandles');
set_param(copyPorts.Outport, 'TestPoint', 'on');
add_block('simulink/Sinks/Out1', [path '/AnalogInputTelemetry'], ...
    'Port', '3', 'Position', [545 240 575 260]);
add_line(path, 'Analog Inputs From/1', 'Analog Inputs Signal Copy/1');
add_line(path, 'Analog Inputs Signal Copy/1', 'AnalogInputTelemetry/1');

% Port 4: a genuine, target-measured count of status-cycle payloads this
% block has emitted (see STATUSCYCLESCRIPT's TXCOUNT comment) -- the CAN
% Write blocks' own driver exposes no cumulative transmit counter, so this
% is the closest real signal to "messages sent" available without adding a
% counter per CAN Write. Lets the GUI show an honest, target-measured
% count instead of the dashed rate column, the same way ACCEPTEDCOUNT
% already does on the RX side.
add_block('simulink/Sinks/Out1', [path '/TransmitCount'], ...
    'Port', '4', 'Position', [745 180 775 200]);
add_line(path, 'Ephorus Status Cycle/3', 'TransmitCount/1');

% Port 5: the shared vehicle state EPHORUSSYSTEMSTATUSSTEP advances from the
% same inverter-plant tick (INVERTERHIL.STEPVEHICLESTATE). Published so the
% synchronized MTi/LWS encoders in ADDHARDWAREBOUNDARY observe the SAME state
% the inverter plant produced this step instead of running as an unrelated
% signal generator -- that shared tick is the whole point of the sensor
% co-simulation. Port 4 is TRANSMITCOUNT above, so this continues at 5;
% master's copy of this file uses port 4 because it has no transmit counter.
add_block('simulink/Sinks/Out1', [path '/VehicleStateFromStatusCycle'], ...
    'Port', '5', 'Position', [745 240 775 260]);
add_line(path, 'Ephorus Status Cycle/4', 'VehicleStateFromStatusCycle/1');

% GUI-commanded per-channel load torque, connected flag, and pair DC-link
% voltage (Fix 2): sourced directly from GUI COMMAND PARAMETERS' Gotos (see
% GUICOMMANDGOTOTAGS). Port 1 is the rate-transitioned observation matrix
% above; these continue directly after it.
% Each Goto above is sourced from a GUI COMMAND PARAMETERS Constant running
