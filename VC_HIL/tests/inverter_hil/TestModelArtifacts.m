        function ephorusRxRetentionRunsFasterThanStatusCycle(testCase)
            % Locks in the CAN RX drain-rate fix: retention (EPHORUS RX
            % RETENTION) must run at the 1 ms base rate so it can pop the
            % FIFO fast enough to keep up with the virtual VCU's five CAN
            % IDs every 5 ms (1000 msg/s); the state machine/plant/CAN-write
            % chain (EPHORUS STATUS CYCLE) must stay on the original 5 ms
            % status-cycle rate the CAN Write blocks require, joined to the
            % fast block by an explicit Rate Transition rather than a
            % silently-inherited one. If either half of this drifts back
            % onto a single shared rate, either the FIFO backs up again or
            % the CAN Write rate collision this split exists to avoid comes
            % back.
            statusPath = [testCase.Model '/Ephorus System Status'];
            retention = [statusPath '/Ephorus RX Retention'];
            carMakerRetention = [statusPath '/CarMaker RX Retention'];
            statusCycle = [statusPath '/Ephorus Status Cycle'];
            rateTransition = [statusPath '/Ephorus RX Observation RT'];
            testCase.verifyNotEqual(getSimulinkBlockHandle(retention), -1);
            testCase.verifyNotEqual( ...
                getSimulinkBlockHandle(carMakerRetention), -1);
            testCase.verifyNotEqual(getSimulinkBlockHandle(statusCycle), -1);
            testCase.verifyNotEqual(getSimulinkBlockHandle(rateTransition), -1);

            testCase.verifyEqual(get_param(retention, 'CompiledSampleTime'), ...
                [0.001 0], 'Ephorus RX Retention must run at the 1 ms base rate.');
            % CarMaker Pedal Retention drains its own channel-1 FIFO at the
            % same 1 ms base rate; the 0x500 pedal demand was split out of
            % Ephorus RX Retention when the CAN bus was divided in two.
            testCase.verifyEqual( ...
                get_param(carMakerRetention, 'CompiledSampleTime'), ...
                [0.001 0], ...
                'CarMaker RX Retention must run at the 1 ms base rate.');
            testCase.verifyEqual(get_param(statusCycle, 'CompiledSampleTime'), ...
                [0.005 0], ['Ephorus Status Cycle must stay on the 5 ms ' ...
                'status-cycle rate the CAN Write blocks require.']);

            portHandles = get_param(retention, 'PortHandles');
            testCase.verifyNumElements(portHandles.Inport, 7, ...
                ['Ephorus RX Retention takes the 6 physical RX fields plus ' ...
                'the CAN control-frame drop mask.']);
            testCase.verifyNumElements(portHandles.Outport, 2, ...
                ['Ephorus RX Retention emits the observation matrix and the ' ...
                'raw control diagnostic; the pedal demand moved to CarMaker ' ...
                'Pedal Retention.']);
            carMakerPorts = get_param(carMakerRetention, 'PortHandles');
            testCase.verifyNumElements(carMakerPorts.Inport, 6, ...
                'CarMaker Pedal Retention takes the 6 physical RX fields.');
            testCase.verifyNumElements(carMakerPorts.Outport, 2, ...
                'CarMaker RX Retention emits pedal demand and physics snapshot.');
            physicsRt = [statusPath '/CarMaker Physics Snapshot RT'];
            testCase.verifyNotEqual(getSimulinkBlockHandle(physicsRt), -1);
            statusPorts = get_param(statusCycle, 'PortHandles');
            testCase.verifyNumElements(statusPorts.Inport, 13, ...
                ['Ephorus Status Cycle takes the rate-transitioned ' ...
                'observation matrix plus the 11 remaining GUI-command ' ...
                'inputs (the 10 inverter/DC-link ones and the steering ' ...
                'angle that drives the shared vehicle state).']);
        end

