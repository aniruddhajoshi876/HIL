    methods (TestClassSetup)
        function loadIoDisconnectedArtifact(testCase)
            testFolder = fileparts(mfilename('fullpath'));
            % TESTFOLDER is VC_HIL/tests/inverter_hil; two levels up is
            % VC_HIL itself, whose generated model/app artifacts and their
            % build/verify/deploy scripts now live one level further in
            % VC_HIL/build.
            vcHilRoot = fileparts(fileparts(testFolder));
            testCase.Root = fullfile(vcHilRoot, 'build');
            addpath(testCase.Root);
            testCase.Root = inverter_hil_setup();
            testCase.assertEqual(version('-release'), '2024b');
            load_system(fullfile(testCase.Root, 'inverter_hil.slx'));
            testCase.Hardware = [testCase.Model ...
                '/Hardware I O - PRE-FLIGHT DISABLED'];
            testCase.assertEqual(get_param(testCase.Hardware, 'Commented'), 'off');
            set_param(testCase.Model, 'SimulationCommand', 'update');
        end
    end

    methods (TestClassTeardown)
        function closeArtifact(testCase)
            if bdIsLoaded(testCase.Model)
                close_system(testCase.Model, 0);
            end
            libraries = {'speedgoatlib_IO183', 'speedgoatlib_IO614'};
            for index = 1:numel(libraries)
                if bdIsLoaded(libraries{index})
                    close_system(libraries{index}, 0);
                end
            end
        end
    end

