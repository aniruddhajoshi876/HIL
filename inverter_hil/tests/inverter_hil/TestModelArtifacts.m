            testCase.verifyTrue(contains(setupText, "'2024b'"));
            testCase.verifyTrue(contains(setupText, ...
                "'inverterhil:WrongRelease'"));

            buildText = fileread(fullfile(testCase.Root, ...
                'build_inverter_hil_model.m'));
            setupPosition = strfind(buildText, 'root = inverter_hil_setup()');
            mutationPosition = strfind(buildText, ...
                'prepareOutput(modelPath, force)');
            testCase.verifyNumElements(setupPosition, 1);
            testCase.verifyNumElements(mutationPosition, 1);
            testCase.verifyLessThan(setupPosition, mutationPosition, ...
                ['The release guard must run before an existing model or ' ...
                'dictionary can be deleted.']);
        end

