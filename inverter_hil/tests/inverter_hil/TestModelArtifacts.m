classdef TestModelArtifacts < matlab.unittest.TestCase
    properties (SetAccess = private)
        Root
        Model = 'inverter_hil'
        Hardware
    end

    methods (TestClassSetup)
        function loadIoDisconnectedArtifact(testCase)
            testFolder = fileparts(mfilename('fullpath'));
            repoRoot = fileparts(fileparts(testFolder));
            testCase.Root = fullfile(repoRoot, 'inverter_hil');
            addpath(testCase.Root);
            testCase.Root = inverter_hil_setup();
            testCase.assertEqual(version('-release'), '2024b');
            load_system(fullfile(testCase.Root, 'inverter_hil.slx'));
            testCase.Hardware = [testCase.Model ...
                '/Hardware I O - PRE-FLIGHT DISABLED'];
            testCase.assertEqual(get_param(testCase.Hardware, 'Commented'), 'on');
            set_param(testCase.Model, 'SimulationCommand', 'update');
        end
    end

    methods (TestClassTeardown)
        function closeArtifact(testCase)
            if bdIsLoaded(testCase.Model)
                close_system(testCase.Model, 0);
            end
            libraries = {'speedgoatlib_IO183', 'speedgoatlib_IO614'};
            for index = 1:numel(libraries)
                if bdIsLoaded(libraries{index})
                    close_system(libraries{index}, 0);
                end
            end
        end
    end

    methods (Test)
        function releaseGuardsPrecedeArtifactMutation(testCase)
            setupText = fileread(fullfile(testCase.Root, ...
                'inverter_hil_setup.m'));
            testCase.verifyTrue(contains(setupText, "version('-release')"));
            testCase.verifyTrue(contains(setupText, "'2024b'"));
            testCase.verifyTrue(contains(setupText, ...
                "'inverterhil:WrongRelease'"));

            buildText = fileread(fullfile(testCase.Root, ...
                'build_inverter_hil_model.m'));
            setupPosition = strfind(buildText, 'root = inverter_hil_setup()');
            mutationPosition = strfind(buildText, ...
                'prepareOutput(modelPath, force)');
            testCase.verifyNumElements(setupPosition, 1);
            testCase.verifyNumElements(mutationPosition, 1);
            testCase.verifyLessThan(setupPosition, mutationPosition, ...
                ['The release guard must run before an existing model or ' ...
                'dictionary can be deleted.']);
        end

        function modelLoadsAndUpdatesWithIoDisconnected(testCase)
            testCase.verifyTrue(bdIsLoaded(testCase.Model));
            testCase.verifyEqual(get_param(testCase.Hardware, 'Commented'), 'on');
            testCase.verifyEmpty(find_system(testCase.Hardware, ...
                'SearchDepth', 1, 'BlockType', 'Inport'));
            testCase.verifyEmpty(find_system(testCase.Hardware, ...
                'SearchDepth', 1, 'BlockType', 'Outport'));
            testCase.verifyWarningFree(@() set_param(testCase.Model, ...
                'SimulationCommand', 'update'));
        end

