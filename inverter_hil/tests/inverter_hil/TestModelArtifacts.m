        function io614CanAndOrderedWritesAreExact(testCase)
            setup = [testCase.Hardware '/IO614 CAN Setup'];
            read = [testCase.Hardware '/IO614 CAN FIFO Read Raw'];
            status = [testCase.Hardware '/IO614 CAN Diagnostics'];
            TestModelArtifacts.verifyParameters(testCase, setup, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'canChn1', 'CAN (HS)'; ...
                'canChn2', 'CAN (HS)'; ...
                'canChn3', 'Disabled'; ...
                'canChn4', 'Disabled'; ...
                'arbBdrChn1', '1.0 MBaud'; ...
                'arbBdrChn2', '1.0 MBaud'});
            % useBusOut ON is required by the RX path, not incidental: the Rx
            % Bus Selector can only split port 2 when it is a CAN_MESSAGE
            % bus. ts is 0.001 (the model's base rate): the virtual VCU
            % transmits five CAN IDs every 5 ms (1000 msg/s), and a single
            % FIFO pop every 5 ms (200 msg/s) permanently fell behind. A
            % naive fix that just raised this ts put the WHOLE status-cycle
            % chain -- state machine, plant, CAN Pack/Write -- on a 1 ms rate
            % that collided with the CAN Write blocks' own explicit 5 ms
            % rate; ephorusRxRetentionRunsFasterThanStatusCycle below locks
            % in the actual fix (retention split into its own 1 ms block,
            % joined to the unchanged 5 ms status-cycle block by a Rate
            % Transition) so neither half of that split can drift back out
            % of sync silently.
            TestModelArtifacts.verifyParameters(testCase, read, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'channel', '1'; ...
                'canType', 'CAN (HS)'; ...
                'useBusOut', 'on'; ...
                'HasMulRead', 'Single Read from Buffer (FIFO)'; ...
                'ts', '0.001'});
            TestModelArtifacts.verifyParameters(testCase, status, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'channel', '1'; ...
                'canType', 'CAN (HS)'; ...
                'autoRecovery', 'off'; ...
                'ts', '0.001'});

            expectedIds = uint32(hex2dec({'383', '385', '393', '395', ...
                '3A3', '3A5', '3B3', '3B5', '400'})).';
            actualIds = zeros(1, 9, 'uint32');
            for index = 1:numel(expectedIds)
                path = sprintf('%s/CAN Write 0x%03X', testCase.Hardware, ...
                    expectedIds(index));
                testCase.verifyNotEqual(getSimulinkBlockHandle(path), -1);
                userData = get_param(path, 'UserData');
                testCase.verifyClass(userData, 'uint32');
                actualIds(index) = userData;
                TestModelArtifacts.verifyParameters(testCase, path, { ...
                    'moduleType', 'IO614'; ...
                    'id', '1'; ...
                    'channel', '1'; ...
                    'canType', 'CAN (HS)'; ...
                    'useBusIn', 'off'; ...
                    'numOfMsg', '1'; ...
                    'enableStatusPort', 'on'; ...
                    'ts', '0.005'; ...
                    'UserDataPersistent', 'on'});
            end
            testCase.verifyEqual(actualIds, expectedIds, ...
                'CAN Write UserData IDs must retain status-cycle order.');
        end

        function ephorusRxRetentionRunsFasterThanStatusCycle(testCase)
            % Locks in the CAN RX drain-rate fix: retention (EPHORUS RX
            % RETENTION) must run at the 1 ms base rate so it can pop the
            % FIFO fast enough to keep up with the virtual VCU's five CAN
            % IDs every 5 ms (1000 msg/s); the state machine/plant/CAN-write
            % chain (EPHORUS STATUS CYCLE) must stay on the original 5 ms
            % status-cycle rate the CAN Write blocks require, joined to the
            % fast block by an explicit Rate Transition rather than a
            % silently-inherited one. If either half of this drifts back
            % onto a single shared rate, either the FIFO backs up again or
            % the CAN Write rate collision this split exists to avoid comes
            % back.
            statusPath = [testCase.Model '/Ephorus System Status'];
            retention = [statusPath '/Ephorus RX Retention'];
            statusCycle = [statusPath '/Ephorus Status Cycle'];
            rateTransition = [statusPath '/Ephorus RX Observation RT'];
            testCase.verifyNotEqual(getSimulinkBlockHandle(retention), -1);
            testCase.verifyNotEqual(getSimulinkBlockHandle(statusCycle), -1);
            testCase.verifyNotEqual(getSimulinkBlockHandle(rateTransition), -1);

            testCase.verifyEqual(get_param(retention, 'CompiledSampleTime'), ...
                [0.001 0], 'Ephorus RX Retention must run at the 1 ms base rate.');
            testCase.verifyEqual(get_param(statusCycle, 'CompiledSampleTime'), ...
                [0.005 0], ['Ephorus Status Cycle must stay on the 5 ms ' ...
                'status-cycle rate the CAN Write blocks require.']);

            portHandles = get_param(retention, 'PortHandles');
            testCase.verifyNumElements(portHandles.Inport, 7, ...
                ['Ephorus RX Retention takes the 6 physical RX fields plus ' ...
                'the CAN control-frame drop mask.']);
            statusPorts = get_param(statusCycle, 'PortHandles');
            testCase.verifyNumElements(statusPorts.Inport, 11, ...
                ['Ephorus Status Cycle takes the rate-transitioned ' ...
                'observation matrix plus the 10 remaining GUI-command ' ...
                'inputs.']);
        end

        function dictionaryContractAndSafeDefaultsAreExact(testCase)
            dictionary = Simulink.data.dictionary.open(fullfile( ...
                testCase.Root, 'inverter_hil.sldd'));
            cleanup = onCleanup(@() close(dictionary)); %#ok<NASGU>
            section = getSection(dictionary, 'Design Data');
            constants = inverterhil.pedalCalibrationConstants();

            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_model_release'), 'R2024b');
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_base_sample_s'), 0.001);
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_status_sample_s'), 0.005);
            % Every GUI-owned tunable is a scalar dictionary entry whose name
            % matches +INVERTERHILGUI/PARAMETERCONTRACT.M's flatPath exactly,
            % so DISCOVERCONTRACT resolves it against the real target. See
            % ADDGUICOMMANDPARAMETERS for the block that keeps each one live
            % through code generation.
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_pedals_throttle'), 0);
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_pedals_brake'), 0);
            testCase.verifyFalse(TestModelArtifacts.value(section, ...
                'hil_cmd_pedals_plausibility_override'));
            testCase.verifyFalse(TestModelArtifacts.value(section, ...
                'hil_cmd_digital_main_button'));
            testCase.verifyFalse(TestModelArtifacts.value(section, ...
                'hil_cmd_digital_cooling_switch'));
            testCase.verifyFalse(TestModelArtifacts.value(section, ...
                'hil_cmd_digital_shutdown_feedback'));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_digital_precharge_sequence'), uint32(0));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_digital_main_button_sequence'), uint32(0));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_dc_link12_v'), 0);
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_dc_link34_v'), 0);
            for channel = 1:4
                testCase.verifyEqual(TestModelArtifacts.value(section, ...
                    sprintf('hil_cmd_inverter%d_load_nm', channel)), 0);
                testCase.verifyTrue(TestModelArtifacts.value(section, ...
                    sprintf('hil_cmd_inverter%d_connected', channel)));
                testCase.verifyEqual(TestModelArtifacts.value(section, ...
                    sprintf('hil_cmd_inverter%d_fault_mask', channel)), ...
                    uint32(0));
                % Pedal endpoints were NaN (deliberately uncalibrated) until
                % 2026-08-02, when they were derived from the VCU firmware's
                % own conversions through its 3.3 V / 65535 ADC domain.
                %
                % The shipped dictionary must match
                % INVERTERHIL.PEDALCALIBRATIONCONSTANTS exactly. An earlier
                % looser check (finite, in 0-5 V, endpoints differ) passed
                % happily on a partly-applied calibration and, more to the
                % point, could not tell a rebuild-wiped dictionary from a
                % recalibrated one -- the NaN wipe it did catch had already
                % shipped to the target. Equality against the version-
                % controlled constants is what makes the wipe loud.
                expected = constants([constants.channel] == channel);
                testCase.assertNumElements(expected, 1);
                releasedV = TestModelArtifacts.value(section, ...
                    sprintf('hil_cal_pedals_released_v%d', channel));
                pressedV = TestModelArtifacts.value(section, ...
                    sprintf('hil_cal_pedals_pressed_v%d', channel));
                testCase.verifyEqual(releasedV, expected.releasedV, ...
                    sprintf(['released_v%d must match ' ...
                    'pedalCalibrationConstants; re-run ' ...
                    'apply_pedal_calibration.'], channel));
                testCase.verifyEqual(pressedV, expected.pressedV, ...
                    sprintf(['pressed_v%d must match ' ...
                    'pedalCalibrationConstants; re-run ' ...
                    'apply_pedal_calibration.'], channel));
                % Still asserted independently of the constants: these are
                % the physical limits of the IO183 output, so a future
                % recalibration that violates them is a defect even though it
                % would agree with itself.
                testCase.verifyGreaterThanOrEqual(releasedV, 0);
                testCase.verifyLessThanOrEqual(releasedV, 5);
                testCase.verifyGreaterThanOrEqual(pressedV, 0);
                testCase.verifyLessThanOrEqual(pressedV, 5);
                testCase.verifyNotEqual(releasedV, pressedV, ...
                    sprintf(['channel %d endpoints must differ or the ' ...
                    'pedal cannot sweep.'], channel));
            end
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_can_drop_control_mask'), uint8(0));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_can_drop_status_mask'), uint16(0));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_cmd_gui_heartbeat'), uint32(0));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_safe_analog_reset_v'), zeros(1, 4));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_safe_digital_reset'), false(1, 8));

            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_control_can_ids'), uint32(hex2dec( ...
                {'186', '196', '1A6', '1B6'})));
            testCase.verifyEqual(TestModelArtifacts.value(section, ...
                'hil_status_can_ids'), uint32(hex2dec( ...
                {'383', '385', '393', '395', '3A3', '3A5', ...
                '3B3', '3B5', '400'})));
            % Torque scale RESOLVED 2026-08-02 by firmware evidence (see
            % INVERTERHIL.PROTOCOL's torqueProfiles.vcu256 comment): the
