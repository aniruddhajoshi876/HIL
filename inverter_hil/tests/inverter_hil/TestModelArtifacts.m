        function io614CanAndOrderedWritesAreExact(testCase)
            setup = [testCase.Hardware '/IO614 CAN Setup'];
            read = [testCase.Hardware '/IO614 CAN FIFO Read Raw'];
            status = [testCase.Hardware '/IO614 CAN Diagnostics'];
            TestModelArtifacts.verifyParameters(testCase, setup, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'canChn1', 'CAN (HS)'; ...
                'canChn2', 'Disabled'; ...
                'canChn3', 'Disabled'; ...
                'canChn4', 'Disabled'; ...
                'arbBdrChn1', '1.0 MBaud'});
            TestModelArtifacts.verifyParameters(testCase, read, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'channel', '1'; ...
                'canType', 'CAN (HS)'; ...
                'useBusOut', 'off'; ...
                'HasMulRead', 'Single Read from Buffer (FIFO)'; ...
                'ts', '0.001'});
            TestModelArtifacts.verifyParameters(testCase, status, { ...
                'moduleType', 'IO614'; ...
                'id', '1'; ...
                'channel', '1'; ...
                'canType', 'CAN (HS)'; ...
                'autoRecovery', 'off'; ...
                'ts', '0.001'});

            expectedIds = uint32(hex2dec({'383', '385', '393', '395', ...
                '3A3', '3A5', '3B3', '3B5', '400'})).';
            actualIds = zeros(1, 9, 'uint32');
            for index = 1:numel(expectedIds)
                path = sprintf('%s/CAN Write 0x%03X', testCase.Hardware, ...
                    expectedIds(index));
                testCase.verifyNotEqual(getSimulinkBlockHandle(path), -1);
                userData = get_param(path, 'UserData');
                testCase.verifyClass(userData, 'uint32');
                actualIds(index) = userData;
                TestModelArtifacts.verifyParameters(testCase, path, { ...
                    'moduleType', 'IO614'; ...
                    'id', '1'; ...
                    'channel', '1'; ...
                    'canType', 'CAN (HS)'; ...
                    'useBusIn', 'off'; ...
                    'numOfMsg', '1'; ...
                    'enableStatusPort', 'on'; ...
                    'ts', '0.005'; ...
                    'UserDataPersistent', 'on'});
            end
            testCase.verifyEqual(actualIds, expectedIds, ...
                'CAN Write UserData IDs must retain status-cycle order.');
        end

