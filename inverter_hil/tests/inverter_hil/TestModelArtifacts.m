        function preflightGateIsEnforcedByTopology(testCase)
            dictionary = Simulink.data.dictionary.open(fullfile( ...
                testCase.Root, 'inverter_hil.sldd'));
            cleanup = onCleanup(@() close(dictionary)); %#ok<NASGU>
            section = getSection(dictionary, 'Design Data');
            testCase.verifyFalse(TestModelArtifacts.value(section, ...
                'hil_hardware_preflight_complete'));
            testCase.verifyEqual(get_param(testCase.Hardware, 'Commented'), 'on');
            initFcn = get_param(testCase.Model, 'InitFcn');
            testCase.verifyTrue(contains(initFcn, ...
                'inverterhil.enforceHardwarePreflight'));
            inverterhil.enforceHardwarePreflight(testCase.Model);
            set_param(testCase.Hardware, 'Commented', 'off');
            restore = onCleanup(@() set_param(testCase.Hardware, ...
                'Commented', 'on')); %#ok<NASGU>
            testCase.verifyError(@() inverterhil.enforceHardwarePreflight( ...
                testCase.Model), 'inverterhil:HardwarePreflightOpen');
        end

        function generatedArtifactsAreIgnoredRepositoryWide(testCase)
            text = fileread(fullfile(testCase.Root, '.gitignore'));
            lines = strip(splitlines(string(text)));
            expected = [".simulink/"; "slprj/"; "*.slxc"; ...
                "*_sg_rtw/"; "*_grt_rtw/"; "*_ert_rtw/"];
            for index = 1:numel(expected)
                testCase.verifyTrue(any(lines == expected(index)), ...
                    sprintf('Missing repository-wide ignore rule: %s', ...
                    expected(index)));
            end
        end

        function annotationDoesNotOverclaimFunctionalCore(testCase)
            channelPaths = arrayfun(@(index) sprintf( ...
                '%s/Ephorus Channel %d', testCase.Model, index), 1:4, ...
                'UniformOutput', false);
            scaffoldOnly = true;
            for index = 1:numel(channelPaths)
                blocks = find_system(channelPaths{index}, 'SearchDepth', 1, ...
                    'Type', 'Block');
                blockTypes = get_param(blocks(2:end), 'BlockType');
                allowed = {'Inport', 'Outport', 'Terminator', 'Constant'};
                scaffoldOnly = scaffoldOnly && all(ismember(blockTypes, allowed));
                testCase.verifyEqual(sum(strcmp(blockTypes, 'Inport')), 4);
                testCase.verifyEqual(sum(strcmp(blockTypes, 'Terminator')), 4);
                testCase.verifyEqual(sum(strcmp(blockTypes, 'Constant')), 3);
                testCase.verifyEqual(sum(strcmp(blockTypes, 'Outport')), 3);
            end
            testCase.verifyTrue(scaffoldOnly, ...
                'Channel topology must be classified from its saved contents.');

            annotations = find_system(testCase.Model, 'FindAll', 'on', ...
                'Type', 'annotation');
            names = get_param(annotations, 'Name');
            if ischar(names)
                names = {names};
            end
            claimsActiveMil = any(cellfun(@(name) contains(name, ...
                'MIL architecture active'), names));
            testCase.verifyFalse(scaffoldOnly && claimsActiveMil, ...
                ['The annotation claims an active MIL architecture, but each ' ...
                'channel terminates every input and emits only safe constants.']);
        end
    end

    methods (Static, Access = private)
        function verifyParameters(testCase, block, expected)
            for index = 1:size(expected, 1)
                testCase.verifyEqual(get_param(block, expected{index, 1}), ...
                    expected{index, 2}, sprintf('%s parameter %s differs.', ...
                    block, expected{index, 1}));
            end
        end

        function result = value(section, name)
            entry = getEntry(section, name);
            result = getValue(entry);
            if isa(result, 'Simulink.Parameter')
                result = result.Value;
            end
        end
    end
