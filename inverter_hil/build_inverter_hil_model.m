add_block('simulink/Signal Attributes/Data Type Conversion', ...
    [path '/' name], 'OutDataTypeStr', 'double', ...
    'Position', [185 y 235 y + 20]);
add_line(path, [sourceName '/1'], [name '/1']);
end

