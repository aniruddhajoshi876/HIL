function script = pedalCalibrationScript()
script = sprintf([ ...
    'function [ao1,ao2,ao3,ao4] = pedalVoltageCalibration( ...\n' ...
    '    throttle, brake, released1, pressed1, released2, pressed2, ...\n' ...
    '    released3, pressed3, released4, pressed4)\n' ...
    '%%PEDALVOLTAGECALIBRATION Map GUI throttle/brake fractions (0-1) to\n' ...
    '%%the four redundant IO183 analog-output voltages using the\n' ...
    '%%calibrated released/pressed endpoints.\n' ...
    '%%\n' ...
    '%%   HIL_CAL_PEDALS_RELEASED_V*/PRESSED_V* ship as NaN precisely so an\n' ...
    '%%   uncalibrated channel is detectable rather than silently plausible\n' ...
    '%%   (INVERTER_HIL_PLAN.MD S3.1 requires each endpoint be measured at\n' ...
    '%%   the connected VCU pin under load). An uncalibrated or out-of-range\n' ...
    '%%   channel therefore drives 0 V -- the same level the IO183 initial\n' ...
    '%%   and reset values use -- instead of propagating NaN into a DAC.\n' ...
    'ao1 = calibratedVolts(released1, pressed1, throttle);\n' ...
    'ao2 = calibratedVolts(released2, pressed2, throttle);\n' ...
    'ao3 = calibratedVolts(released3, pressed3, brake);\n' ...
    'ao4 = calibratedVolts(released4, pressed4, brake);\n' ...
    'end\n' ...
    '\n' ...
    'function volts = calibratedVolts(releasedV, pressedV, fraction)\n' ...
    'if ~isfinite(releasedV) || ~isfinite(pressedV) || ~isfinite(fraction)\n' ...
    '    volts = 0;\n' ...
    '    return\n' ...
    'end\n' ...
    'bounded = min(max(fraction, 0), 1);\n' ...
    'volts = releasedV + (pressedV - releasedV) * bounded;\n' ...
    '%%The IO183 analog outputs are configured for the 0..5 V range.\n' ...
    'volts = min(max(volts, 0), 5);\n' ...
    'end\n']);
end

function script = prechargePulseScript()
script = sprintf([ ...
    'function active = prechargePulseFromCounter(counter)\n' ...
    '%%PRECHARGEPULSEFROMCOUNTER Turn a GUI counter increment into a\n' ...
    '%%fixed-width PRECH_BTN_IN pulse (INVERTER_HIL_PLAN.MD S7.1: "Model\n' ...
    '%%generates a deterministic precharge pulse on counter change").\n' ...
    '%%200 ms (at the model''s 1 ms base rate) is provisional pending\n' ...
    '%%confirmation against VCU firmware precharge-button timing.\n' ...
    'persistent prevCounter ticksRemaining initialized\n' ...
    'pulseTicks = uint32(200);\n' ...
    'if isempty(initialized)\n' ...
    '    prevCounter = counter;\n' ...
    '    ticksRemaining = uint32(0);\n' ...
    '    initialized = true;\n' ...
    'end\n' ...
    'if counter ~= prevCounter\n' ...
    '    ticksRemaining = pulseTicks;\n' ...
    '    prevCounter = counter;\n' ...
    'end\n' ...
    '%%Emitted as double because that is what the IO183 Digital Output\n' ...
    '%%port takes.\n' ...
    'active = double(ticksRemaining > uint32(0));\n' ...
    'if ticksRemaining > uint32(0)\n' ...
    '    ticksRemaining = ticksRemaining - uint32(1);\n' ...
    'end\n' ...
    'end\n']);
end

function addGuiCommandParameters(model)
%ADDGUICOMMANDPARAMETERS Reference every GUI-owned tunable so it survives
%code generation as an addressable SETPARAM/GETPARAM target.
%
%   +INVERTERHILGUI/PARAMETERCONTRACT.M declares 33 logical names with a flat
%   scalar dictionary backing (plan open decision 16 selected flat scalars;
%   see spikes/decision16/FINDINGS.md). A Simulink.Parameter that no block
%   references is pruned during code generation, so each one here drives a
%   Constant into a Terminator: a legitimate, permanent signal sink that
%   keeps the block live without implying the GUI value affects channel
%   behavior.
%
%   The pedal, digital-stimulus, and pedal-calibration tunables are also
%   referenced inside the hardware boundary, where they genuinely drive the
%   IO183 analog and digital outputs (see ADDHARDWAREBOUNDARY). Their
%   terminated Constants here are retained so those names still survive code
%   generation when the boundary is commented out. The remaining tunables
%   (per-inverter load/connected/fault masks, DC-link commands, CAN drop
%   masks, heartbeat) are still terminated only: Ephorus Channel 1-4 remain
%   constant-zero scaffold, so those GUI values do not yet affect behavior.

path = [model '/GUI Command Parameters'];
add_block('simulink/Ports & Subsystems/Subsystem', path, ...
    'Position', [1560 90 1900 480]);
clearSubsystem(path);

scalarDouble = { ...
    'hil_cmd_pedals_throttle'; 'hil_cmd_pedals_brake'; ...
    'hil_cmd_dc_link12_v'; 'hil_cmd_dc_link34_v'};
scalarBoolean = { ...
    'hil_cmd_pedals_plausibility_override'; ...
    'hil_cmd_digital_main_button'; 'hil_cmd_digital_cooling_switch'; ...
    'hil_cmd_digital_shutdown_feedback'};
scalarUint32 = { ...
    'hil_cmd_digital_precharge_sequence'; ...
    'hil_cmd_digital_main_button_sequence'; 'hil_cmd_gui_heartbeat'};
scalarUint8 = {'hil_cmd_can_drop_control_mask'};
scalarUint16 = {'hil_cmd_can_drop_status_mask'};
for channel = 1:4
    scalarDouble{end + 1, 1} = sprintf('hil_cmd_inverter%d_load_nm', channel); %#ok<AGROW>
    scalarBoolean{end + 1, 1} = sprintf('hil_cmd_inverter%d_connected', channel); %#ok<AGROW>
    scalarUint32{end + 1, 1} = sprintf('hil_cmd_inverter%d_fault_mask', channel); %#ok<AGROW>
    scalarDouble{end + 1, 1} = sprintf('hil_cal_pedals_released_v%d', channel); %#ok<AGROW>
    scalarDouble{end + 1, 1} = sprintf('hil_cal_pedals_pressed_v%d', channel); %#ok<AGROW>
end

y = 30;
y = addParameterGroup(path, scalarDouble, '', y);
y = addParameterGroup(path, scalarBoolean, 'boolean', y);
y = addParameterGroup(path, scalarUint32, 'uint32', y);
y = addParameterGroup(path, scalarUint8, 'uint8', y);
addParameterGroup(path, scalarUint16, 'uint16', y);
end

function y = addParameterGroup(path, names, dataType, y)
for index = 1:numel(names)
    name = names{index};
    options = {'Value', name, 'SampleTime', '0.001', ...
        'Position', [35 y 165 y + 20]};
    if ~isempty(dataType)
        options = [options, {'OutDataTypeStr', dataType}]; %#ok<AGROW>
    end
    add_block('simulink/Sources/Constant', [path '/Cmd ' name], options{:});
    add_block('simulink/Sinks/Terminator', [path '/Term ' name], ...
        'Position', [200 y 220 y + 20]);
    add_line(path, ['Cmd ' name '/1'], ['Term ' name '/1']);
    y = y + 26;
end
end

