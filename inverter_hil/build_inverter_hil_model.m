function name = addNamedParameterSource(path, paramName, y, dataType)
%ADDNAMEDPARAMETERSOURCE Bring a dictionary tunable into a subsystem as a
%signal by naming it as a Constant block's Value (same convention as
%ADDPARAMETERGROUP), so the block resolves and stays live/tunable against
%the data dictionary without needing a workspace lookup inside generated
%code.
if nargin < 4
    dataType = '';
end
name = ['Ref ' paramName];
options = {'Value', paramName, 'SampleTime', '0.001', ...
    'Position', [25 y 155 y + 20]};
if ~isempty(dataType)
    options = [options, {'OutDataTypeStr', dataType}]; %#ok<AGROW>
end
add_block('simulink/Sources/Constant', [path '/' name], options{:});
end

function name = addDoubleCast(path, sourceName, y)
