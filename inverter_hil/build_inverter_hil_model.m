function buildSystemStatus(path)
clearSubsystem(path);
for index = 1:8
    addTerminatedInput(path, sprintf('StatusInput%d', index), index, 15 + 35 * index);
end
% StatusInput1-8 (each channel's Status3X3/Status3X5) stay terminated:
% Ephorus Channel 1-4 remain constant-zero scaffold (see
% ANNOTATIONDOESNOTOVERCLAIMFUNCTIONALCORE), so this cycle is computed
% independently by INVERTERHIL.STEPMODEL using its own persistent state
% rather than by combining those still-fake per-channel outputs.
fcnPath = [path '/Ephorus Status Cycle'];
add_block('simulink/User-Defined Functions/MATLAB Function', fcnPath, ...
    'Position', [300 45 480 220]);
setMatlabFunctionScript(fcnPath, statusCycleScript());
add_block('simulink/Sinks/Out1', [path '/OrderedStatusPayloads'], ...
    'Port', '1', 'Position', [545 120 575 140]);
add_line(path, 'Ephorus Status Cycle/1', 'OrderedStatusPayloads/1');

% Received control frames, published by the hardware boundary. Feeding them
% in is what lets a commanding VCU move the channels out of Idle; with no
% frames the retained bank stays empty and the model holds Idle exactly as
% before.
rxTags = {'EphorusRxDataPresent', 'EphorusRxId', 'EphorusRxExtended', ...
    'EphorusRxRemote', 'EphorusRxLength', 'EphorusRxData'};
for index = 1:numel(rxTags)
    fromName = sprintf('%s From', rxTags{index});
    add_block('simulink/Signal Routing/From', [path '/' fromName], ...
        'GotoTag', rxTags{index}, ...
        'Position', [60, 30 + 30 * index, 220, 50 + 30 * index]);
    add_line(path, [fromName '/1'], ...
        sprintf('Ephorus Status Cycle/%d', index), 'autorouting', 'on');
end
end

