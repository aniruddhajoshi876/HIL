function script = rxRetentionScript()
%RXRETENTIONSCRIPT Drain the CAN Read FIFO and retain frames at this
%block's own rate (the CAN Read block's ts, 1 ms -- see BUILDCANINTERFACE).
%The virtual VCU transmits five CAN IDs (the pedal broadcast plus four
%control frames) every 5 ms, 1000 msg/s; a single FIFO pop every 5 ms only
%drains 200 msg/s, so the receive FIFO permanently fell behind and the
%retained command was stale at best and, once the FIFO backed up, simply
%frozen -- frames genuinely sent were never read. Draining at 1 ms matches
%the production rate. EPHORUS STATUS CYCLE (STATUSCYCLESCRIPT) keeps the
%state machine, plant, and CAN-write chain at the original 5 ms rate.
script = sprintf([ ...
    'function rxObservation = ephorusRxRetentionStep( ...\n' ...
    '    rxDataPresent, rxId, rxExtended, rxRemote, rxLength, rxData, ...\n' ...
    '    dropControlMask)\n' ...
    '%%#codegen\n' ...
    '%%EPHORUSRXRETENTIONSTEP Drain one CAN Read FIFO pop per call and\n' ...
    '%%retain it, at this block''s own 1 ms rate. See BUILD_INVERTER_HIL_\n' ...
    '%%MODEL''s RXRETENTIONSCRIPT for why: the virtual VCU''s five CAN IDs\n' ...
    '%%every 5 ms (1000 msg/s) outran a single 5 ms FIFO pop (200 msg/s).\n' ...
    '%%\n' ...
    '%%A frame is ALWAYS passed, with DROP set when nothing was received.\n' ...
    '%%RECEIVECONTROLFRAME rejects a dropped frame without touching the\n' ...
    '%%bank, so the array stays fixed-size for code generation instead of\n' ...
    '%%growing and shrinking. Nothing is fabricated: no data present means\n' ...
    '%%no command retained.\n' ...
    '%%\n' ...
    '%%BANK/STATUSBANK/TICKMS are persistent so retention survives across\n' ...
    '%%calls, exactly as the single combined block this was split out of\n' ...
    '%%used to carry it.\n' ...
    'persistent bank statusBank tickMs\n' ...
    'if isempty(bank)\n' ...
    '    bank = inverterhil.initialDecoderBank();\n' ...
    '    statusBank = inverterhil.initialStatusBank();\n' ...
    '    tickMs = uint32(0);\n' ...
    'end\n' ...
    '%%(:)'' normalises the bus Data element to a 1x8 row regardless of the\n' ...
    '%%orientation Simulink propagates, matching the proven pattern in the\n' ...
    '%%IO614 CAN visibility test decoder.\n' ...
    'payload = uint8(rxData(:))'';\n' ...
    'frame = struct( ...\n' ...
    '    ''id'', uint32(rxId), ...\n' ...
    '    ''dlc'', uint8(rxLength), ...\n' ...
    '    ''payload'', payload, ...\n' ...
    '    ''isExtended'', logical(rxExtended), ...\n' ...
    '    ''isRemote'', logical(rxRemote), ...\n' ...
    '    ''drop'', ~logical(rxDataPresent));\n' ...
    'statusBank = inverterhil.receiveStatusFrame(statusBank, frame, tickMs);\n' ...
    '%%The CAN control-frame drop mask (Fix 4) is applied to a COPY of the\n' ...
    '%%received frame used only for retention -- STATUSBANK above already\n' ...
    '%%saw the unmodified FRAME, so this mask cannot affect the received-\n' ...
    '%%status-frame path, only whether a control frame is retained into the\n' ...
    '%%decoder bank.\n' ...
    'controlFrame = inverterhil.applyControlDropMask(frame, uint8(dropControlMask));\n' ...
    'bank = inverterhil.receiveControlFrame(bank, controlFrame, tickMs);\n' ...
    '%%RXOBSERVATION is taken BEFORE the tick advances, so the ages it\n' ...
    '%%reports are measured against the same tick the frame above was\n' ...
    '%%retained at. Advancing first would make a frame received this step\n' ...
    '%%appear one period old.\n' ...
    'controlRows = inverterhil.rxObservation(bank, tickMs);\n' ...
    'statusRows = inverterhil.statusObservation(statusBank, tickMs);\n' ...
    'rxObservation = zeros(13, 14);\n' ...
    'rxObservation(1:4, :) = controlRows;\n' ...
    'rxObservation(5:13, 1:11) = statusRows;\n' ...
    '%%TICKMS is REAL MILLISECONDS, advanced by 1 per call at this block''s\n' ...
    '%%own 1 ms period. The MOD wrap matches DECODERSNAPSHOT''s rollover-\n' ...
    '%%safe modulo arithmetic; MATLAB uint32 addition otherwise SATURATES\n' ...
    '%%(the generated C++ made that explicit: if (t + 1U < t) { t =\n' ...
    '%%MAX_uint32_T; }) and would freeze the counter at intmax rather than\n' ...
    '%%roll over, which would freeze every retained frame at age 0 forever\n' ...
    '%%and stop command timeouts from firing entirely.\n' ...
    'tickMs = uint32(mod(double(tickMs) + 1, 4294967296));\n' ...
    'end\n']);
end

function script = statusCycleScript()
% PACKSTATUSCYCLE returns a struct (ids/dlc/payloads); only the 9x8 uint8
% PAYLOADS matrix leaves this block, because emitting a bare struct from a
% MATLAB Function block would require a Simulink.Bus definition. The IDs are
% already fixed by the CAN Pack/CAN Write pair for each frame, and the DLC is
% a constant 8, so nothing is lost by dropping them here.
script = sprintf([ ...
    'function [payloads, rxObservationOut, txCount, vehicleState] = ...\n' ...
    '        ephorusSystemStatusStep( ...\n' ...
    '    rxObservation, ...\n' ...
    '    loadNm1, loadNm2, loadNm3, loadNm4, ...\n' ...
    '    connected1, connected2, connected3, connected4, ...\n' ...
    '    dcLink12V, dcLink34V, steeringAngleDeg)\n' ...
    '%%#codegen\n' ...
    '%%EPHORUSSYSTEMSTATUSSTEP Advance the real, persistent-state Ephorus\n' ...
    '%%status cycle (see INVERTERHIL.STEPMODEL) and emit its nine 8-byte\n' ...
    '%%payloads, at the 5 ms status-cycle rate. Single source of truth:\n' ...
    '%%the hardware boundary reads PAYLOADS through a Goto/From pair rather\n' ...
    '%%than recomputing it.\n' ...
    '%%\n' ...
    '%%CAN retention itself now happens upstream in EPHORUS RX RETENTION,\n' ...
    '%%at that block''s own 1 ms rate -- fast enough to keep up with the\n' ...
    '%%virtual VCU''s five-CAN-ID, 5 ms burst, which a single 5 ms FIFO pop\n' ...
    '%%could not drain (see RXRETENTIONSCRIPT). RXOBSERVATION arrives here\n' ...
    '%%as that block''s flattened 13x14 matrix, rate-transitioned down to\n' ...
    '%%this block''s own 5 ms rate (see BUILD_INVERTER_HIL_MODEL''s\n' ...
    '%%BUILDSYSTEMSTATUS). This block was deliberately NOT sped up to 1 ms\n' ...
    '%%itself: doing that once made the whole chain -- state machine,\n' ...
    '%%plant, and the CAN Pack/Write pair this block feeds -- run at 1 ms\n' ...
    '%%too, which collided with the CAN Write blocks'' own explicit 5 ms\n' ...
    '%%rate (see BUILDCANINTERFACE''s CAN Read comment and\n' ...
    '%%TESTMODELARTIFACTS'' io614CanAndOrderedWritesAreExact guard).\n' ...
    '%%Splitting retention out is what lets the FIFO drain fast without\n' ...
    '%%moving the status/torque cadence off its real 5 ms hardware\n' ...
    '%%contract.\n' ...
    '%%\n' ...
    '%%Each channel''s command is re-decoded here from RXOBSERVATION''s own\n' ...
    '%%retained payload bytes with the SAME INVERTERHIL.DECODECONTROLFRAME\n' ...
    '%%the GUI and RXOBSERVATION already use, so this can never disagree\n' ...
    '%%with what the RX table shows.\n' ...
    '%%\n' ...
    '%%BANK persists only for COMMANDOUTOFDOMAIN, which is latched (plan:\n' ...
    '%%once set it stays set until the application restarts) and so cannot\n' ...
    '%%be re-derived from a single RXOBSERVATION snapshot; every other BANK\n' ...
    '%%field is refreshed from RXOBSERVATION below before use. TICKMS here\n' ...
    '%%is a fixed local reference, not a running clock: this block no\n' ...
    '%%longer measures command age itself -- RXOBSERVATION column 11\n' ...
    '%%already carries it, correctly measured against EPHORUS RX\n' ...
    '%%RETENTION''s real 1 ms clock -- so LASTVALIDTICKMS below is set to\n' ...
    '%%make DECODERSNAPSHOT''s own age formula (TICKMS - LASTVALIDTICKMS,\n' ...
    '%%mod 2^32) reproduce that exact value rather than measuring a second,\n' ...
    '%%inconsistent one.\n' ...
    '%%\n' ...
    '%%TXCOUNT is a genuine, target-measured count of status-cycle payloads\n' ...
    '%%this block has emitted -- one real per-call increment, not an\n' ...
    '%%estimate derived from elapsed host time (the CAN Write blocks''\n' ...
    '%%own driver exposes no cumulative transmit counter, so this is the\n' ...
    '%%actual count of cycles this block computed, which in normal\n' ...
    '%%operation, i.e. HIL_CMD_CAN_DROP_STATUS_MASK == 0, is exactly the\n' ...
    '%%count of frames each CAN Write actually sent). Shared across all 9\n' ...
    '%%status IDs since they are packed together every call; a caller\n' ...
    '%%wanting a genuinely independent per-ID count would need one counter\n' ...
    '%%per CAN Write''s own Tx Control gate instead. Held in its own\n' ...
    '%%persistent TXCOUNTER, distinct from the TXCOUNT output variable:\n' ...
    '%%Simulink''s MATLAB Function analysis could not determine output\n' ...
    '%%sizes/types for this block when a single variable was both\n' ...
    '%%persistent and a direct function output.\n' ...
    'persistent state plantState bank txCounter vehicleStateBank\n' ...
    'if isempty(state)\n' ...
    '    state = inverterhil.initialSystemState();\n' ...
    '    plantState = inverterhil.initialPlantState();\n' ...
    '    bank = inverterhil.initialDecoderBank();\n' ...
    '    txCounter = uint32(0);\n' ...
    '    vehicleStateBank = [0 0 0 0];\n' ...
    'end\n' ...
    'tickMs = uint32(0);\n' ...
    'controlIds = inverterhil.protocol().controlIds;\n' ...
    'for channelIndex = 1:4\n' ...
    '    bank.hasCommand(channelIndex) = rxObservation(channelIndex, 9) ~= 0;\n' ...
    '    if bank.hasCommand(channelIndex)\n' ...
    '        framePayload = uint8(rxObservation(channelIndex, 1:8));\n' ...
    '        [~, ~, command] = inverterhil.decodeControlFrame( ...\n' ...
    '            controlIds(channelIndex), uint8(8), framePayload, false, false);\n' ...
    '        bank.commands(channelIndex) = command;\n' ...
    '        ageMs = rxObservation(channelIndex, 11);\n' ...
    '        bank.lastValidTickMs(channelIndex) = ...\n' ...
    '            uint32(mod(double(tickMs) - ageMs, 4294967296));\n' ...
    '    end\n' ...
    'end\n' ...
    '%%EXTERNALINPUTS carries the GUI-commanded per-channel load torque, DC\n' ...
    '%%link pair voltage (dcLink12V feeds channels 1-2, dcLink34V feeds\n' ...
    '%%channels 3-4, matching ADDARCHITECTURE''s dcPort = 1 + (channel > 2)\n' ...
    '%%convention), and connected flag into STEPMODEL -- see\n' ...
    '%%INVERTERHIL.DEFAULTEXTERNALINPUTS for why faultMask is left at its\n' ...
    '%%default (no consumer exists for it yet).\n' ...
    'externalInputs = inverterhil.defaultExternalInputs();\n' ...
    'externalInputs.channels(1).loadTorqueNm = double(loadNm1);\n' ...
    'externalInputs.channels(2).loadTorqueNm = double(loadNm2);\n' ...
    'externalInputs.channels(3).loadTorqueNm = double(loadNm3);\n' ...
    'externalInputs.channels(4).loadTorqueNm = double(loadNm4);\n' ...
    'externalInputs.channels(1).connected = logical(connected1);\n' ...
    'externalInputs.channels(2).connected = logical(connected2);\n' ...
    'externalInputs.channels(3).connected = logical(connected3);\n' ...
    'externalInputs.channels(4).connected = logical(connected4);\n' ...
    'externalInputs.channels(1).dcLinkV = double(dcLink12V);\n' ...
    'externalInputs.channels(2).dcLinkV = double(dcLink12V);\n' ...
    'externalInputs.channels(3).dcLinkV = double(dcLink34V);\n' ...
    'externalInputs.channels(4).dcLinkV = double(dcLink34V);\n' ...
    '%%FRAMES is a single always-dropped frame: retention already happened\n' ...
    '%%upstream in EPHORUS RX RETENTION, so STEPMODEL must not retain\n' ...
    '%%anything a second time here. Its REJECTEDCOUNT/LASTREJECTCODE side\n' ...
    '%%effect on that dropped frame is therefore not this block''s\n' ...
    '%%bookkeeping -- RXOBSERVATIONOUT below carries EPHORUS RX\n' ...
    '%%RETENTION''s own correctly-tracked columns 13-14 straight through\n' ...
    '%%instead. Only COMMANDOUTOFDOMAIN, which STEPMODEL sets as a side\n' ...
    '%%effect of building PLANTINPUT from the freshly-decoded commands\n' ...
    '%%above, is read back from NEXTBANK.\n' ...
    'droppedFrame = struct(''id'', uint32(0), ''dlc'', uint8(0), ...\n' ...
    '    ''payload'', zeros(1, 8, ''uint8''), ''isExtended'', false, ...\n' ...
    '    ''isRemote'', false, ''drop'', true);\n' ...
    '[state, plantState, cycle, ~, plantOutput, nextBank] = inverterhil.stepModel( ...\n' ...
    '    state, plantState, tickMs, inverterhil.defaultStateConfig(), ...\n' ...
    '    inverterhil.defaultCalibration(), bank, droppedFrame, ...\n' ...
    '    externalInputs);\n' ...
    'bank.commandOutOfDomain = nextBank.commandOutOfDomain;\n' ...
    '%%The MTi/LWS observations are sampled from the SAME PLANTOUTPUT this\n' ...
    '%%tick produced, so the sensor frames and the inverter status frames\n' ...
    '%%are observations of one vehicle rather than three unrelated signal\n' ...
    '%%generators. VEHICLESTATE leaves this block on port 4 and reaches the\n' ...
    '%%encoders through the HILSHAREDVEHICLESTATE Goto/From pair.\n' ...
    '[vehicleStateBank, vehicleState] = inverterhil.stepVehicleState( ...\n' ...
    '    vehicleStateBank, plantOutput, double(steeringAngleDeg), ' ...
    num2str(statusPeriodS()) ');\n' ...
    'payloads = cycle.payloads;\n' ...
    'rxObservationOut = rxObservation;\n' ...
    'rxObservationOut(1:4, 12) = double(bank.commandOutOfDomain(:));\n' ...
    'txCounter = uint32(mod(double(txCounter) + 1, 4294967296));\n' ...
    'txCount = txCounter;\n' ...
    'end\n']);
end

