function addGuiCommandParameters(model)
%ADDGUICOMMANDPARAMETERS Reference every GUI-owned tunable so it survives
%code generation as an addressable SETPARAM/GETPARAM target.
%
%   +INVERTERHILGUI/PARAMETERCONTRACT.M declares 33 logical names with a flat
%   scalar dictionary backing (plan open decision 16 selected flat scalars;
%   see spikes/decision16/FINDINGS.md). A Simulink.Parameter that no block
%   references is pruned during code generation, so each one here drives a
%   Constant into either a Terminator (a legitimate, permanent signal sink
%   that keeps the block live without implying the GUI value affects channel
%   behavior) or, for the tunables listed in GOTOTAGFOR below, a global Goto
%   that carries the value to a real consumer elsewhere in the model --
%   EPHORUSSTATUSCYCLESCRIPT (Fix 2: load/connected/dc-link) or the hardware
%   boundary's status-frame Tx Control gate (Fix 4: CAN drop masks).
%
%   The pedal, digital-stimulus, and pedal-calibration tunables are also
%   referenced inside the hardware boundary, where they genuinely drive the
%   IO183 analog and digital outputs (see ADDHARDWAREBOUNDARY). Their
%   terminated Constants here are retained so those names still survive code
%   generation when the boundary is commented out. The Goto-routed tunables
%   below do NOT need that same backup: their real consumers (EPHORUS SYSTEM
%   STATUS and its MATLAB Function blocks) live outside the hardware
%   boundary and are unaffected by its Commented flag, so a single Goto here
%   is the only live reference they need. The remaining tunable
%   (per-inverter fault_mask) is still terminated only: no function in
%   +INVERTERHIL/ consumes a per-channel fault-injection bitmask today (see
%   INVERTERHIL.DEFAULTEXTERNALINPUTS), so wiring it would invent behavior
%   that does not exist; left as a documented follow-up.

path = [model '/GUI Command Parameters'];
add_block('simulink/Ports & Subsystems/Subsystem', path, ...
    'Position', [1560 90 1900 480]);
clearSubsystem(path);

scalarDouble = { ...
    'hil_cmd_pedals_throttle'; 'hil_cmd_pedals_brake'; ...
    'hil_cmd_xcp_pedals_throttle'; 'hil_cmd_xcp_pedals_brake'; ...
    'hil_cmd_steering_angle_deg'; ...
    'hil_cmd_dc_link12_v'; 'hil_cmd_dc_link34_v'};
scalarBoolean = { ...
    'hil_cmd_steering_dropout'; 'hil_cmd_imu_dropout'; ...
    'hil_cmd_pedals_plausibility_override'; ...
    'hil_cmd_digital_main_button'; 'hil_cmd_digital_cooling_switch'; ...
    'hil_cmd_digital_shutdown_feedback'; 'hil_cmd_xcp_pedals_active'};
scalarUint32 = { ...
    'hil_cmd_digital_precharge_sequence'; ...
    'hil_cmd_digital_main_button_sequence'; 'hil_cmd_gui_heartbeat'};
scalarUint8 = {'hil_cmd_can_drop_control_mask'};
scalarUint16 = {'hil_cmd_can_drop_status_mask'};
for channel = 1:4
    scalarDouble{end + 1, 1} = sprintf('hil_cmd_inverter%d_load_nm', channel); %#ok<AGROW>
    scalarBoolean{end + 1, 1} = sprintf('hil_cmd_inverter%d_connected', channel); %#ok<AGROW>
    scalarUint32{end + 1, 1} = sprintf('hil_cmd_inverter%d_fault_mask', channel); %#ok<AGROW>
    scalarDouble{end + 1, 1} = sprintf('hil_cal_pedals_released_v%d', channel); %#ok<AGROW>
    scalarDouble{end + 1, 1} = sprintf('hil_cal_pedals_pressed_v%d', channel); %#ok<AGROW>
end

gotoTags = guiCommandGotoTags();

y = 30;
y = addParameterGroup(path, scalarDouble, '', y, gotoTags);
y = addParameterGroup(path, scalarBoolean, 'boolean', y, gotoTags);
y = addParameterGroup(path, scalarUint32, 'uint32', y, gotoTags);
y = addParameterGroup(path, scalarUint8, 'uint8', y, gotoTags);
addParameterGroup(path, scalarUint16, 'uint16', y, gotoTags);
end

function tags = guiCommandGotoTags()
%GUICOMMANDGOTOTAGS Map of GUI Command Parameters tunable name -> global
%Goto tag, for the tunables ADDPARAMETERGROUP routes to a real consumer
%instead of a Terminator (Fix 2 and Fix 4). Any name not a key here keeps
%the original Constant -> Terminator dead-end.
tags = containers.Map('KeyType', 'char', 'ValueType', 'char');
tags('hil_cmd_dc_link12_v') = 'GuiCmdDcLink12V';
tags('hil_cmd_dc_link34_v') = 'GuiCmdDcLink34V';
tags('hil_cmd_can_drop_control_mask') = 'GuiCmdCanDropControlMask';
tags('hil_cmd_can_drop_status_mask') = 'GuiCmdCanDropStatusMask';
tags('hil_cmd_steering_angle_deg') = 'GuiCmdSteeringAngleDeg';
tags('hil_cmd_steering_dropout') = 'GuiCmdSteeringDropout';
tags('hil_cmd_imu_dropout') = 'GuiCmdImuDropout';
for channel = 1:4
    tags(sprintf('hil_cmd_inverter%d_load_nm', channel)) = ...
        sprintf('GuiCmdInverter%dLoadNm', channel);
    tags(sprintf('hil_cmd_inverter%d_connected', channel)) = ...
        sprintf('GuiCmdInverter%dConnected', channel);
end
end

function y = addParameterGroup(path, names, dataType, y, gotoTags)
if nargin < 5
    gotoTags = containers.Map('KeyType', 'char', 'ValueType', 'char');
end
for index = 1:numel(names)
    name = names{index};
    options = {'Value', name, 'SampleTime', '0.001', ...
        'Position', [35 y 165 y + 20]};
    if ~isempty(dataType)
        options = [options, {'OutDataTypeStr', dataType}]; %#ok<AGROW>
    end
    add_block('simulink/Sources/Constant', [path '/Cmd ' name], options{:});
    if isKey(gotoTags, name)
        add_block('simulink/Signal Routing/Goto', [path '/Goto ' name], ...
            'GotoTag', gotoTags(name), 'TagVisibility', 'global', ...
            'Position', [200 y 260 y + 20]);
        add_line(path, ['Cmd ' name '/1'], ['Goto ' name '/1']);
    else
        add_block('simulink/Sinks/Terminator', [path '/Term ' name], ...
            'Position', [200 y 220 y + 20]);
        add_line(path, ['Cmd ' name '/1'], ['Term ' name '/1']);
    end
    y = y + 26;
end
end

