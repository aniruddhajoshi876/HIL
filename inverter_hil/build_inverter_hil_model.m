    '    lastSteeringDeg = double(steeringAngleDeg);\n' ...
    'end\n' ...
    'angleDeg = double(steeringAngleDeg);\n' ...
    'acceleration = packMti680Payload(''acceleration'', vehicleState(1:3));\n' ...
    'rateOfTurn = packMti680Payload(''rateofturn'', vehicleState(4:6));\n' ...
    '%%LWS_SPEED is the STEERING WHEEL angular speed -- the Bosch datasheet\n' ...
    '%%defines it as "Angular speed", 0 to 1016 deg/s at 4 deg/s resolution,\n' ...
    '%%i.e. the rate of change of LWS_ANGLE. It is NOT the vehicle yaw rate,\n' ...
    '%%which is a different physical quantity on a different sensor (the\n' ...
    '%%MTi rate-of-turn frame above already carries yaw rate). Derived here\n' ...
    '%%from the commanded angle over this block''s own period and clamped\n' ...
    '%%into the encoder range so a fast dial sweep cannot range-error\n' ...
    '%%PACKLWSPAYLOAD.\n' ...
    'speedDegPerS = min(1016, abs(angleDeg - lastSteeringDeg) / ' ...
    num2str(statusPeriodS()) ');\n' ...
    'lastSteeringDeg = angleDeg;\n' ...
    'steering = packLwsPayload(angleDeg, speedDegPerS, uint8(7));\n' ...
    'enableAcceleration = uint32(~logical(imuDropout));\n' ...
    'enableRateOfTurn = enableAcceleration;\n' ...
    '%%The LWS updates at 100 Hz / 10 ms (datasheet "CAN update rate") and\n' ...
    '%%this block runs at the 5 ms status rate, so every second tick\n' ...
    '%%transmits. A dropout is a genuine absence on the wire (Tx Control\n' ...
    '%%low), not a zeroed payload.\n' ...
    'enableSteering = uint32(~logical(steeringDropout) && mod(phase, 2) == 0);\n' ...
    'phase = uint8(mod(double(phase) + 1, 2));\n' ...
    'end\n']);
end

function value = statusPeriodS()
%STATUSPERIODS The Ephorus status-cycle period, in seconds.
%   Single source of truth for every CAN Write 'ts' and the
%   HIL_STATUS_SAMPLE_S dictionary entry. The CAN Read block and
%   EPHORUS RX RETENTION run at the model's 1 ms base rate instead (see
%   BUILDCANINTERFACE's CAN Read comment) -- only the state-machine/
%   plant/CAN-write side of the status cycle, in EPHORUS STATUS CYCLE,
%   still runs at this rate.
value = 0.005;
end

