    'function [f1,f2,f3,f4,f5,f6,f7,f8,f9] = ephorusStatusCycleFrames(payloads)\n' ...
    '%%EPHORUSSTATUSCYCLEFRAMES Split the nine-frame status cycle into the\n' ...
