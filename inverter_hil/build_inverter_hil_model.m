function clearSubsystem(path)
lineHandles = get_param(path, 'LineHandles');
fields = fieldnames(lineHandles);
for index = 1:numel(fields)
    handles = lineHandles.(fields{index});
    handles = handles(handles ~= -1);
    for handle = handles(:)'
        try %#ok<TRYNC>
            delete_line(handle);
        end
    end
end
blocks = find_system(path, 'SearchDepth', 1, 'Type', 'Block');
for index = 2:numel(blocks)
    delete_block(blocks{index});
end
end

function addHardwareBoundary(model)
load_system('canlib');
path = [model '/Hardware I O - PRE-FLIGHT DISABLED'];
add_block('simulink/Ports & Subsystems/Subsystem', path, ...
    'Position', [960 505 1500 720], ...
    'BackgroundColor', 'orange', ...
    'AttributesFormatString', ...
    ['LIVE - Commented flag and hil_hardware_preflight_complete both\n' ...
     'gate this subsystem open per operator hands-on IO183 attestation']);
clearSubsystem(path);

io183 = add_block('speedgoatlib_IO183/Setup', [path '/IO183 Setup'], ...
    'Position', [25 30 160 100]);
set_param(io183, 'parModuleId', '1', 'parPciSlot', '-1', ...
    'parDaSimult', 'on', 'parAdCoupling', 'Single Ended', ...
    'parAdRange', '0..5V', 'parAdChannelLow', '1', ...
    'parAdChannelHigh', '4', 'parDaChannels', '[1 2 3 4]', ...
    'parDaRange', '0..5V', 'parDaInit', '[0 0 0 0]', ...
    'parDaReset', '[0 0 0 0]', 'parDoChannels', '[1 2 3 4 5 6 7 8]', ...
    'parDoInit', '[0 0 0 0 0 0 0 0]', ...
    'parDoReset', '[0 0 0 0 0 0 0 0]', ...
    'parDiChannels', '[9 10 11 12 13]', ...
    'parIOPullReferenceFront', 'Pull-down');

ao = add_block('speedgoatlib_IO183/Analog Output', ...
    [path '/IO183 AO01-AO04 Safe Zero'], 'Position', [25 130 170 185]);
set_param(ao, 'parModuleId', '1', 'parSampTime', '0.001', ...
    'parDaSimult', 'on', 'parDaChannels', '[1 2 3 4]', ...
    'parDaInit', '[0 0 0 0]', 'parDaReset', '[0 0 0 0]');
ai = add_block('speedgoatlib_IO183/Analog Input', ...
    [path '/IO183 AI01-AI04 Rail Monitor'], 'Position', [25 215 170 270]);
set_param(ai, 'parModuleId', '1', 'parSampTime', '0.001', ...
    'parAdChannelLow', '1', 'parAdChannelHigh', '4');
dio = add_block('speedgoatlib_IO183/Digital Output', ...
    [path '/IO183 DIO01-DIO08 Safe Zero'], 'Position', [25 300 170 355]);
set_param(dio, 'parModuleId', '1', 'parSampTime', '0.001', ...
    'parDoChannels', '[1 2 3 4 5 6 7 8]', ...
    'parDoInit', '[0 0 0 0 0 0 0 0]', ...
    'parDoReset', '[0 0 0 0 0 0 0 0]');
di = add_block('speedgoatlib_IO183/Digital Input', ...
    [path '/IO183 DIO09-DIO13 VCU Monitor'], 'Position', [25 385 170 440]);
set_param(di, 'parModuleId', '1', 'parSampTime', '0.001', ...
    'parDiChannels', '[9 10 11 12 13]');

setup = add_block('speedgoatlib_IO614/CAN and LIN Setup ', ...
    [path '/IO614 CAN Setup'], 'Position', [235 30 390 100]);
set_param(setup, 'moduleType', 'IO614', 'id', '1', ...
    'canChn1', 'CAN (HS)', 'canChn2', 'Disabled', ...
    'canChn3', 'Disabled', 'canChn4', 'Disabled', ...
    'arbBdrChn1', '1.0 MBaud');
read = add_block('speedgoatlib_IO614/CAN Read ', ...
    [path '/IO614 CAN FIFO Read Raw'], 'Position', [235 130 390 190]);
% useBusOut is ON so port 2 is a CAN_MESSAGE bus the Rx Bus Selector can
% split into ID/Extended/Remote/Length/Data. With it off the port is not a
% bus and the selector cannot resolve it.
% ts is 0.005, matching the status-cycle and CAN Write rate. The received
% frame drives EPHORUSSYSTEMSTATUSSTEP, whose output feeds the CAN Pack/Write
% pair; reading at 0.001 made that whole chain 1 ms and collided with the
% 5 ms writes.
%
% TRADEOFF, stated plainly: this is a single FIFO read per 5 ms tick, so the
% model consumes at most 200 control frames per second. That is comfortable
% for typical VCU command rates but WILL under-drain a burst, and the
% IO614's 501-message receive buffer would then back up. If frames are ever
% missed, the fix is a rate transition on the payload path so the read can
% run at 1 ms while the status cycle stays at 5 ms -- not simply raising
% this rate, which would break the 5 ms status contract.
set_param(read, 'moduleType', 'IO614', 'id', '1', 'channel', '1', ...
    'canType', 'CAN (HS)', 'useBusOut', 'on', ...
    'HasMulRead', 'Single Read from Buffer (FIFO)', ...
    'LabelInHex', 'on', 'ts', '0.005');
% Received Ephorus control frames leave the boundary through global Gotos,
% mirroring how the transmitted payloads enter it. EPHORUSSYSTEMSTATUSSTEP
% retains them into its decoder bank so the four channels can actually
% respond to a commanding VCU (see INVERTERHIL.STEPMODEL).
%
% NOTE: this is the first signal that flows OUT of the boundary. The
% transmitted-payload Goto lives outside and the boundary only reads it, so
% commenting the boundary left that path intact. These Gotos are inside, so
% commenting the boundary removes them and the matching Froms below lose
% their source. The boundary is currently live and its preflight gate was
% bypassed by operator decision, so that is not a live problem -- but it is
% a real narrowing of the "boundary can be commented out" property and must
% be restored (for example by grounding the Froms) if that gate returns.
rxSelector = add_block('simulink/Signal Routing/Bus Selector', ...
    [path '/Rx Bus Selector'], 'Position', [455 480 465 570]);
set_param(rxSelector, 'OutputSignals', 'ID,Extended,Remote,Length,Data');
add_line(path, 'IO614 CAN FIFO Read Raw/2', 'Rx Bus Selector/1', ...
    'autorouting', 'on');

rxTags = {'EphorusRxDataPresent', 'EphorusRxId', 'EphorusRxExtended', ...
    'EphorusRxRemote', 'EphorusRxLength', 'EphorusRxData'};
% Port 1 of the read block is "Data present"; ports 1-5 of the selector are
% ID, Extended, Remote, Length, Data in the order set above.
rxSources = {'IO614 CAN FIFO Read Raw/1', 'Rx Bus Selector/1', ...
    'Rx Bus Selector/2', 'Rx Bus Selector/3', 'Rx Bus Selector/4', ...
    'Rx Bus Selector/5'};
for index = 1:numel(rxTags)
    gotoName = sprintf('%s Goto', rxTags{index});
    add_block('simulink/Signal Routing/Goto', [path '/' gotoName], ...
        'GotoTag', rxTags{index}, 'TagVisibility', 'global', ...
        'Position', [540, 470 + 30 * index, 700, 490 + 30 * index]);
    add_line(path, rxSources{index}, [gotoName '/1'], 'autorouting', 'on');
end

status = add_block('speedgoatlib_IO614/CAN Status ', ...
    [path '/IO614 CAN Diagnostics'], 'Position', [235 220 390 280]);
set_param(status, 'moduleType', 'IO614', 'id', '1', 'channel', '1', ...
    'canType', 'CAN (HS)', 'autoRecovery', 'off', 'ts', '0.001');

ids = hex2dec({'383', '385', '393', '395', '3A3', ...
    '3A5', '3B3', '3B5', '400'});
for index = 1:numel(ids)
    row = mod(index - 1, 5);
    column = floor((index - 1) / 5);
    block = add_block('speedgoatlib_IO614/CAN Write ', ...
        sprintf('%s/CAN Write 0x%03X', path, ids(index)), ...
        'Position', [455 + 190 * column, 30 + 80 * row, ...
        610 + 190 * column, 85 + 80 * row]);
    set_param(block, 'moduleType', 'IO614', 'id', '1', ...
        'channel', '1', 'canType', 'CAN (HS)', 'useBusIn', 'off', ...
        'numOfMsg', '1', 'enableStatusPort', 'on', 'ts', '0.005', ...
        'UserData', uint32(ids(index)), 'UserDataPersistent', 'on', ...
        'Description', sprintf('Ordered Ephorus status ID 0x%03X', ids(index)));
end

% Each CAN Write above (Speedgoat 'CAN' message-type mode) expects a single
% CAN_MESSAGE-typed input, which only a CAN Pack block produces -- not the
% eight raw bytes on their own. The real, correctly bit-packed nine-frame
% cycle is computed once in Ephorus System Status (see INVERTERHIL.STEPMODEL)
% and reaches this port-free subsystem through the global Goto/From tag, so
% the frames transmitted are exactly the payloads the rest of the model sees.
add_block('simulink/Signal Routing/From', [path '/Status Payloads From'], ...
    'GotoTag', 'EphorusStatusPayloads', 'Position', [25 470 160 490]);
framesFcnPath = [path '/Ephorus Status Cycle Frames'];
add_block('simulink/User-Defined Functions/MATLAB Function', framesFcnPath, ...
    'Position', [235 320 420 460]);
setMatlabFunctionScript(framesFcnPath, statusCycleFramesScript());
add_line(path, 'Status Payloads From/1', 'Ephorus Status Cycle Frames/1');
for index = 1:numel(ids)
    packName = sprintf('CAN Pack 0x%03X', ids(index));
    packPath = [path '/' packName];
