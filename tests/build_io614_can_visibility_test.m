    'Value', 'tx_id', 'Position', [40 850 160 880]);
add_block('simulink/Sources/Constant', [model '/tx_dlc Param'], ...
    'Value', 'tx_dlc', 'Position', [40 900 160 930]);
add_block('simulink/Sources/Constant', [model '/tx_payload_u8 Param'], ...
    'Value', 'tx_payload_u8', 'Position', [40 950 160 980]);
add_block('simulink/Sources/Constant', [model '/tx_period_ms Param'], ...
    'Value', 'tx_period_ms', 'Position', [40 1000 160 1030]);

add_block('simulink/User-Defined Functions/MATLAB Function', ...
    [model '/Tx Generator'], 'Position', [220 800 420 900]);
setMatlabFunctionScript(model, 'Tx Generator', txGeneratorScript());

add_line(model, 'tx_enable Param/1', 'Tx Generator/1', 'autorouting', 'on');
add_line(model, 'tx_period_ms Param/1', 'Tx Generator/2', 'autorouting', 'on');
add_line(model, 'Model Time/1', 'Tx Generator/3', 'autorouting', 'on');

add_block('simulink/Sources/Constant', [model '/Tx Extended (0)'], ...
    'Value', 'uint8(0)', 'Position', [480 720 560 745]);
add_block('simulink/Sources/Constant', [model '/Tx Remote (0)'], ...
    'Value', 'uint8(0)', 'Position', [480 760 560 785]);
add_block('simulink/Sources/Constant', [model '/Tx Error (0)'], ...
    'Value', 'uint8(0)', 'Position', [480 800 560 825]);
add_block('simulink/Sources/Constant', [model '/Tx Timestamp (0)'], ...
    'Value', 'double(0)', 'Position', [480 840 560 865]);

add_block('simulink/Signal Routing/Bus Creator', [model '/Tx Bus Creator'], ...
    'Inputs', '7', 'Position', [620 700 720 900]);

busFieldNames = {'Extended', 'Length', 'Remote', 'Error', 'ID', ...
    'Timestamp', 'Data'};

setLineName(add_line(model, 'Tx Extended (0)/1', 'Tx Bus Creator/1', ...
    'autorouting', 'on'), busFieldNames{1});
setLineName(add_line(model, 'tx_dlc Param/1', 'Tx Bus Creator/2', ...
    'autorouting', 'on'), busFieldNames{2});
setLineName(add_line(model, 'Tx Remote (0)/1', 'Tx Bus Creator/3', ...
    'autorouting', 'on'), busFieldNames{3});
setLineName(add_line(model, 'Tx Error (0)/1', 'Tx Bus Creator/4', ...
    'autorouting', 'on'), busFieldNames{4});
setLineName(add_line(model, 'tx_id Param/1', 'Tx Bus Creator/5', ...
    'autorouting', 'on'), busFieldNames{5});
setLineName(add_line(model, 'Tx Timestamp (0)/1', 'Tx Bus Creator/6', ...
    'autorouting', 'on'), busFieldNames{6});
setLineName(add_line(model, 'tx_payload_u8 Param/1', 'Tx Bus Creator/7', ...
    'autorouting', 'on'), busFieldNames{7});

write = add_block('speedgoatlib_IO614/CAN Write ', [model '/IO614 CAN Write'], ...
    'Position', [780 780 980 840]);
set_param(write, 'moduleType', 'IO614', 'id', '1', 'channel', '1', ...
    'canType', 'CAN (HS)', 'useBusIn', 'on', 'numOfMsg', '1', ...
    'enableInput', 'on', 'enableStatusPort', 'on', 'ts', '0.001');

add_line(model, 'Tx Generator/1', 'IO614 CAN Write/1', 'autorouting', 'on');
add_line(model, 'Tx Bus Creator/1', 'IO614 CAN Write/2', 'autorouting', 'on');

add_block('simulink/Signal Routing/Demux', [model '/Tx Payload Demux'], ...
    'Outputs', '8', 'Position', [780 700 790 780]);
add_line(model, 'tx_payload_u8 Param/1', 'Tx Payload Demux/1', 'autorouting', 'on');

addNamedOutport(model, 'tx_enable', 1040, 700, 'tx_enable Param', 1);
addNamedOutport(model, 'tx_id_dec', 1040, 730, 'tx_id Param', 1);
addNamedOutport(model, 'tx_id_hex', 1040, 760, 'tx_id Param', 1);
addNamedOutport(model, 'tx_dlc', 1040, 790, 'tx_dlc Param', 1);
addNamedOutport(model, 'tx_period_ms', 1040, 820, 'tx_period_ms Param', 1);
addNamedOutport(model, 'tx_count', 1040, 850, 'Tx Generator', 2);
addNamedOutport(model, 'can_write_status', 1040, 880, 'IO614 CAN Write', 1);
for byte = 0:7
    addNamedOutport(model, sprintf('tx_payload_b%d', byte), 1040, ...
        910 + 30 * byte, 'Tx Payload Demux', byte + 1);
end
end

function addDiagnostics(model)
status = add_block('speedgoatlib_IO614/CAN Status ', [model '/IO614 CAN Diagnostics'], ...
    'Position', [40 1080 240 1180]);
set_param(status, 'moduleType', 'IO614', 'id', '1', 'channel', '1', ...
    'canType', 'CAN (HS)', 'autoRecovery', 'off', 'ts', '0.001');

diagNames = {'can_bus_load', 'can_bus_off', 'can_recovery_count', ...
    'can_transmit_pending', 'can_receive_overrun', 'can_error_warning'};
for index = 1:numel(diagNames)
    addNamedOutport(model, diagNames{index}, 300, ...
        1090 + 30 * (index - 1), 'IO614 CAN Diagnostics', index);
end
end

function addNamedOutport(model, name, x, y, srcBlock, srcPort)
outBlock = add_block('simulink/Sinks/Out1', [model '/' name], ...
    'Position', [x y x + 40 y + 20]);
portNumber = str2double(get_param(outBlock, 'Port'));
set_param(outBlock, 'Port', num2str(portNumber));
add_line(model, sprintf('%s/%d', srcBlock, srcPort), [name '/1'], ...
    'autorouting', 'on');
end

function setLineName(lineHandle, name)
set_param(lineHandle, 'Name', name);
end

function setMatlabFunctionScript(model, blockName, script)
rt = sfroot;
chart = rt.find('-isa', 'Stateflow.EMChart', 'Path', [model '/' blockName]);
chart.Script = script;
end

function script = rxDecoderScript()
script = strjoin({ ...
    'function [rx_valid, rx_id, rx_is_extended, rx_is_remote, rx_dlc, ...' , ...
    '    rx_payload_u8, rx_count, rx_last_timestamp, rx_interarrival_ms] = ...', ...
    '    fcn(validIn, idIn, extIn, remIn, dlcIn, dataIn, tsIn, tNow)', ...
    '%#codegen', ...
    'persistent latchedId latchedExt latchedRem latchedDlc latchedData', ...
    'persistent latchedTs count lastValidMs interarrivalMs', ...
    'if isempty(latchedId)', ...
    '    latchedId = uint32(0);', ...
    '    latchedExt = uint8(0);', ...
    '    latchedRem = uint8(0);', ...
    '    latchedDlc = uint8(0);', ...
    '    latchedData = uint8(zeros(1, 8));', ...
    '    latchedTs = double(0);', ...
    '    count = uint32(0);', ...
    '    lastValidMs = double(-1);', ...
    '    interarrivalMs = double(0);', ...
    'end', ...
    'nowMs = tNow * 1000;', ...
    'if validIn', ...
    '    latchedId = uint32(idIn);', ...
    '    latchedExt = uint8(extIn);', ...
    '    latchedRem = uint8(remIn);', ...
    '    latchedDlc = uint8(dlcIn);', ...
    '    latchedData = uint8(dataIn(:))'';', ...
    '    latchedTs = double(tsIn);', ...
    '    count = count + uint32(1);', ...
    '    if lastValidMs >= 0', ...
    '        interarrivalMs = nowMs - lastValidMs;', ...
    '    end', ...
    '    lastValidMs = nowMs;', ...
    'end', ...
    'rx_valid = logical(validIn);', ...
    'rx_id = latchedId;', ...
    'rx_is_extended = latchedExt;', ...
    'rx_is_remote = latchedRem;', ...
    'rx_dlc = latchedDlc;', ...
    'rx_payload_u8 = latchedData;', ...
    'rx_count = count;', ...
    'rx_last_timestamp = latchedTs;', ...
    'rx_interarrival_ms = interarrivalMs;', ...
    'end'}, sprintf('\n'));
end

function script = txGeneratorScript()
% send is the IO614 CAN Write "Tx Control" input: uint32(1) transmits
% the current bus contents this step, uint32(0) skips transmission.
script = strjoin({ ...
    'function [send, tx_count] = fcn(txEnable, periodMs, tNow)', ...
    '%#codegen', ...
    'persistent lastSendMs count', ...
    'if isempty(lastSendMs)', ...
    '    lastSendMs = double(-1);', ...
    '    count = uint32(0);', ...
    'end', ...
    'nowMs = tNow * 1000;', ...
    'safePeriod = max(periodMs, 1);', ...
    'send = uint32(0);', ...
    'if txEnable && (lastSendMs < 0 || (nowMs - lastSendMs) >= safePeriod)', ...
    '    send = uint32(1);', ...
    '    lastSendMs = nowMs;', ...
    '    count = count + uint32(1);', ...
    'end', ...
    'tx_count = count;', ...
    'end'}, sprintf('\n'));
end

function addAnnotation(model, text, position, color)
annotation = Simulink.Annotation(model, text);
annotation.Position = position;
annotation.BackgroundColor = color;
annotation.FontWeight = 'bold';
end

function closeIfLoaded(model)
if bdIsLoaded(model)
    close_system(model, 0);
end
end
