/* CAN entry is the CAN message as stored in the DPRAM of IO601. 
 * 
 * Extremely important: if a struct is non aligned on 32 bits, some gap
 * will be autogenerated by the compiler.
 *
 */


typedef struct QUEUEENTRY
{
    uint32_T word[5];
}QUEUEENTRY;




