/**************************************************************************
 * This function returns the identifier given in parameter, coded in 
 * Motorola format.
 *
 * Motorola uses a Big Endian format, this means that:
 *
 * In a word (4 bytes):
 * 
 * Intel[0] = Motorola[3]
 * Intel[1] = Motorola[2]
 * Intel[2] = Motorola[1]
 * Intel[3] = Motorola[0] 
 *
 * Important, if the data is not complete (size != 32), we have to align
 * it.
 *************************************************************************/
static uint32_T ConvertIdentifier(uint32_T id, uint32_T nBits)
{
    uint32_T motorola;
    
    motorola = (id << (32 - nBits));
    motorola = (uint32_T)(((motorola & 0x000000FF) << 24) + 
                          ((motorola & 0x0000FF00) << 8) +
                          ((motorola & 0x00FF0000) >> 8) +
                          ((motorola & 0xFF000000) >> 24));
    return motorola;
}

/**************************************************************************
 *               
 * a CAN entry contains up to 20 elements, which are:
 *|---------------------------------------|
 *|  n    |   standard    |    extended   |
 *|---------------------------------------|
 *|  0    |   status      |  status       |
 *|  1    |   count       |  count        | 
 *|  2    |   TimeStamp   |  TimeStamp    |
 *|  3    |   TimeStamp   |  TimeStamp    |
 *|  4    |   TimeStamp   |  TimeStamp    |
 *|  5    |   TimeStamp   |  TimeStamp    |
 *|  6    |   Type        |  Type         |
 *|  7    |   Information |  Information  |
 *|  8    |   Identifier  |  Identifier   |
 *|  9    |   Identifier  |  Identifier   |
 *| 10    |   Data        |  Identifier   |
 *| 11    |   Data        |  Identifier   |
 *| 12    |   Data        |  Data         |
 *| 13    |   Data        |  Data         |
 *| 14    |   Data        |  Data         |
 *| 15    |   Data        |  Data         |
 *| 16    |   Data        |  Data         |
 *| 17    |   Data        |  Data         |
 *| 18    |   Reserved    |  Data         |
 *| 19    |   Reserved    |  Data         |
 *|---------------------------------------/
 *
 * TimeStamp is not relevant. Because the MC generates it.
 * Type is always 0 for sending
 * 
 * Information is:
 * Bits 0-3: DLC (up to 8 bytes).
 * Bits 4-5: reserved
 * Bits 6  : remote frame (0: data frame, 1: remote frame)
 * Bits 7  : frame format (0: standard, 1: extended) 
 *     
 *************************************************************************/
static uint8_T PrepareQueueEntry(canMsg message, QUEUEENTRY *pQueue)
{
    uint8_T status, nBytes, information; 
    uint16_T standardID;
    uint32_T extendedID;
    
    status = pQueue->word[0] & 0xFF;
    if (status == 0) // is the queue free to be written?
    {
        if (message.Extended)
        {
            status = 1;
            nBytes = 10 + message.Length;
            information = message.Length | (message.Remote << 6) | (message.Extended << 7);
            extendedID = ConvertIdentifier(message.ID, 29);
            
            pQueue->word[1] = (information << 24);
            pQueue->word[2] = (extendedID);
            pQueue->word[3] = (message.Data[3] << 24) | (message.Data[2] << 16) | (message.Data[1] << 8) | message.Data[0]; 
            pQueue->word[4] = (message.Data[7] << 24) | (message.Data[6] << 16) | (message.Data[5] << 8) | message.Data[4]; 
            pQueue->word[0] = (nBytes << 8) | (status);
        }
        else
        {
            status = 1;
            nBytes = 8 + message.Length;
            information = (message.Length) | (message.Remote << 6) | (message.Extended << 7);
            standardID = ConvertIdentifier(message.ID, 11);
            
            pQueue->word[1] = (information << 24);
            pQueue->word[2] = (message.Data[1] << 24) | (message.Data[0] << 16) | standardID;
            pQueue->word[3] = (message.Data[5] << 24) | (message.Data[4] << 16) | (message.Data[3] << 8) | message.Data[2];
            pQueue->word[4] = (message.Data[7] << 8) | message.Data[6];  
            pQueue->word[0] = (nBytes << 8) | (status);
        }
        return 1;
    }
    else
    {
        return 0;
    }                
}

static int8_T SendCANMessage(SimStruct *S, int32_T port, canMsg message)
{  
    
    /*
     * Variable declaration:
     */
    int32_T frc, position;
    QUEUEENTRY *pQueue;
    uint32_T base;
        
    /*
     * Initialization
     */
    base = ssGetIWorkValue(S, BASE_ADDR_I_IND);
    frc = 0;
    
    
    /* 1. We determine if the frame can be sent or no. */   
    if (port != 1 && port != 2) 
    {
        frc = -10;
    }

    switch (message.Extended)
    {    
        case 0:
            if (message.ID > 2047)
            {
                frc = -12; //in standard, identifer cannot be larger than 2^11 - 1
            }
            break;

        case 1:
            if (message.ID > 536870911)
            {
                frc = -13; //in extended, identifer cannot be larger than 2^19 - 1
            }
            break;
            
        default:
            frc = -11; // not a correct frame format.
            break;
    }
    
    if (message.Length > 8)
    {
        frc = -14;
    }
    
    /* when the frames passed all the tests, we send it. A negative ident
       is a "don't send this message" flag. */
    if (frc == 0 && message.ID >= 0)
    {   

        if (port == 1)
        {
            
            position = ptrWritePointer1[(uint32_T)mxGetPr(MODULEID_ARG)[0] - 1]; // get the current buffer position for port 1.
            //printf("position: %d\n", position);
            
            //printf("0x%X\n", base + 0x50 + position * sizeof(QUEUEENTRY));
            pQueue = (QUEUEENTRY *)(base + 0x50 + position * sizeof(QUEUEENTRY));
        }
        else
        {
            position = ptrWritePointer2[(uint32_T)mxGetPr(MODULEID_ARG)[0] - 1]; // get the current buffer position for port 2.
            pQueue = (QUEUEENTRY *)(base + 0x438 + position * sizeof(QUEUEENTRY));  
        }
        
        /* now the CAN message has to be placed in the queueentry. */
        if (PrepareQueueEntry(message, pQueue))
        {

            /* increment the position in the DPRAM buffer (0 to 49)*/
            position = (position == 49)? 0 : ++position;

            /* save the position */
            if (port == 1)
            {
                ptrWritePointer1[(uint32_T)mxGetPr(MODULEID_ARG)[0] - 1] = position;
            }
            else
            {
                ptrWritePointer2[(uint32_T)mxGetPr(MODULEID_ARG)[0] - 1] = position;
            }
        }
        else
        {
            frc = -1; /* the queue entry wasn't free. */
        }
    
    }    
                
    return frc;
    
}
